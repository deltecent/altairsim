;
;
;	VERSION 3.0 OF DDBIOS IS CAPABLE OF SUPPORTING BOTH
;	DOUBLE DENSITY AND SINGLE DENSITY FORMATS ON EITHER
;	THE 8" OR THE 5" DRIVES. DDBIOS V3.0 WILL SUPPORT USE
;	OF EITHER THE 1795 OR THE 1791 CONTROLLER CHIPS.
;
;	VERSION 3.1 ALLOWS COLD BOOT FROM HARD DISK WITHOUT 
;	FLOPPY DISKS IN SYSTEM
;
;	*****************************************
;	*					*
;	*                                       *
;	*	The BOOT routine dumps track 0	*
;	*	SECTOR 1 data to address 0080H.	*
;	*					*
;	*****************************************
;
	PSECT	ABS
	ORG	 0F000H
;
;
;
;
COBYTE	EQU	031H	;CAP-CPP CHK DATA
COBSYS	EQU	0E800H	;CAP-CPP SYS ADDR
MNBYTE	EQU	0E0H	;MONITOR CHECK DATA
MNITR	EQU	0E002H	;MONITOR CHECK ADDR
MONITR	EQU	0E003H	;MONITOR ENTRY POINT
HDBIOS	EQU	0E800H	;HARD DISC LINKAGE
NBYTES	EQU	128	;BYTES PER SECTOR
;
;
RBASE	EQU	0000H		; START OF RAM
TADDR	EQU	RBASE+40H	; TRANSFER ADDRESS
UNIT	EQU	RBASE+42H	; NEW UNIT BYTE
SCTR	EQU	RBASE+43H	; SECTOR
TRK	EQU	RBASE+44H	; TRACK
NREC	EQU	RBASE+45H	; # OF SECTORS
ERMASK	EQU	RBASE+46H	; ERROR MASK
ERSTAT	EQU	RBASE+47H	; ERROR STATUS
IDSV	EQU	RBASE+48H	; 4 BYTES
SIDE	EQU	RBASE+49H	; ID SIDE BYTE
CMDSV	EQU	RBASE+4CH	; COMMAND SAVE
SPSV	EQU	RBASE+4DH	; SP SAVE (2 BYTES)
CICHR	EQU	RBASE+4FH	; USED FOR BACKSPACE
TEMP1	EQU	RBASE+50H	; 1 BYTE TEMPORARY REG
TEMP2	EQU	RBASE+51H	; 2 BYTE TEMPORARY REG
IXSAV	EQU	RBASE+53H	; IX STORE BUFFER
UNITCK	EQU	RBASE+55H	; OLD UNIT BYTE
RSEEK	EQU	RBASE+56H	; NBR OF RESEEKS
RTRY	EQU	RBASE+57H	; NBR OF RTRYS
SSTACK	EQU	RBASE+80H	; SYSTEM STACK
COLD	EQU	RBASE+80H	; COLD START ADDRESS
;
;
;
;	PORTS USED BY DISK CONTROLLER
;
X	EQU	60H
RSET	EQU	X+0	; CONTROLLER RESET ADDR
SELECT	EQU	X+3	; DRIVE SELECT PORT
STATUS	EQU	X+4	; STATUS PORT
TRACK	EQU	X+5	; TRACK PORT
SECTOR	EQU	X+6	; SECTOR PORT
DATA	EQU	X+7	; DATA PORT
CMD	EQU	X+4	; COMMAND PORT
	EJECT
;
;
;
;
; DISK ERROR STATUS BITS (ERSTAT)
;
;
; BIT 7 - DRIVE NOT READY
; BIT 6 - WRITE PROTECTED
; BIT 5 - TRACK SEEK ERROR
; BIT 4 - SECTOR NOT FOUND
; BIT 3 - CRC ERROR
; BIT 2 - DATA LOST
; BIT 1 - DRQ BIT
; BIT 0 - WRITE DELETED SECTOR READ
; FEH - CONTROLLER HANG UP
; 0FH - INVALID TRACK ERROR
;
;
; DISK CONTROLLER COMMAND CODES
;
;
RDACMD	EQU	0C0H	; READ ADDRESS CMD
RDCMD	EQU	88H	; READ SECTOR CMD
WRCMD	EQU	0A8H	; WRITE SECTOR CMD
WRTCMD	EQU	0F4H	; WRITE TRACK CMD
;
;
	EJECT
;
;	SDOS SYSTEM LINKAGES
;
;
BIOS	NOP		; RESET ENTRY FOR SINGLE 
	LD	E,0 ;*
;	NOP
;	NOP		;SDOS CODE
WBOOTE	JP	BOOT 	; WARM START ENTRY
CSE	JP	0E006H 	; TRNSFR CTL TO MONITOR
CIE	JP	0E009H 	;   "     "   "    "
COE	JP	0E00CH 	;   "     "   "    "
DTYPE	JP	UNITSL 	; SET UP UNIT BYTE
	NOP
	NOP
	NOP
	NOP
	NOP
	NOP
HME	JP	HOME 	; MOVE DISK TO TRK 00
SDSKE	JP	SELDSK 	; SELECT DISK DRIVE
STRKE	JP	SETTRK 	; SET DISK TRACK
SSECE	JP	SETSEC 	; SET DISK SECTOR
SDMAE	JP	SETDMA 	; SET MEM ADDR FOR READ/WRITE
RDE	JP	READ 	; READ A SECTOR
WRE	JP	WRITE 	; WRITE A SECTOR
LDE	JP	LOADER 	; LOAD 'N' SECTORS
SVE	JP	SAVER 	; SAVE 'N' RECORDS
FMATE	JP	FMAT 	; FORMAT A DISKETTE
;
	EJECT
;
;
;	THE FOLLOWING TABLES CONTAIN DEFINITIONS
;	WHICH VARY ACCORDING TO DRIVE TYPE.
;
;
;
;	8" SINGLE DENSITY DRIVE VARIABLES
;
;
	ORG	0F03FH
STDSDT:	DEFB	26	;SECTORS PER TRACK
	DEFB	77	;TRACKS PER SIDE
	DEFB	100-27	;INDEX HEADER GAP
	DEFB	 6	;GAP 1
	DEFB	11	;GAP 2
	DEFB	27	;GAP 3
	DEFB	08H	;RESTORE CMD
	DEFB	18H	;SEEK NO VERIFY CMD
	DEFB	1CH	;SEEK WITH VERIFY
;
;
;	8" DOUBLE DENSITY DRIVE VARIABLES
;
;
STDDDT:	DEFB	50		;SECTRS/TRACK
	DEFB	77		;TRACKS/SIDE
	DEFB	100-16		;HEADER GAP
	DEFB	8		;GAP 1
	DEFB	22		;GAP 2
	DEFB	16		;GAP 3
	DEFB	8		;RESTORE CMD
	DEFB	18H		;SEEK NO VERIFY
	DEFB	1CH             ;SEEK WITH VERIFY
;
;
;	8" 256 BYTE DOUBLE DENSITY VARIABLES
;
;
DDT256:	DEFB	26	;NBR SCTRS/TRK
	DEFB	77	;NBR TRKS
	DEFB	100-54	;INDEX HEADR GAP
	DEFB	8	;NBR GAP1 BYTES
	DEFB	22	;NBR GAP2 BYTES
	DEFB	54	;NBR GAP3 BYTES
	DEFB	08H	;RESTORE CMD
	DEFB	18H	;SK/NO VERIFY
	DEFB	1CH	;SK/WTH VERIFY
;
;
;
	EJECT
;
;
;	5" SINGLE DENSITY DISK VARIABLES
;
;
MINSDT	DEFB	18	;NBR OF SECTRS PER TRACK
	DEFB	35	;NBR OF TRACKS PER SIDE
	DEFB	20-8	;INDEX HEADER GAP
	DEFB	 6	;NBR BYTES IN GAP 1 (PRE ID GAP)
	DEFB	11	;NBR BYTES IN GAP 2 (ID->DATA GAP)
	DEFB	 8	;NBR BYTES IN GAP 3 ( DATA-->ID GAP)
	DEFB	0BH	;RESTORE CMD
	DEFB	1BH	;SEEK NO VERIFY CMD
	DEFB	1FH	;SEEK WITH VERIFY
;
;
;
;	5" DOUBLE DENSITY DISK VARIABLES
;
;
MINDDT	DEFB	29	;NBR OF SECTORS PER TRACK
	DEFB	35	;NBR OF TRACKS PER SIDE	
	DEFB	100-16	;NBR OF HEADER GAP BYTES
	DEFB	8	;GAP 1 (PRE ID)
	DEFB	22	;GAP 2 (ID->DATA GAP)
	DEFB	16	;GAP 3 (DATA-->ID GAP)
	DEFB	0BH	;RESTORE COMMAND
	DEFB	1BH	;SEEK NO VERIFY CMD
	DEFB	1FH	;SEEK WITH VERIFY
;
;
;	THE FOLLOWING EQUATES RELATE THE ABOVE FORMAT
;	TABLES TO THE INDEX REGISTER (IX).
;
;
NSCTRS	EQU	0
NTRKS	EQU	1
HEADR	EQU	2
GAP1	EQU	3
GAP2	EQU	4
GAP3	EQU	5
RSCMD	EQU	6
SKNCMD	EQU	7
SKCMD	EQU	8
;
;
	EJECT
;
;	BOOT LOADS A SECTOR FROM DISK TO ADDR 0080H AFTER
;	CHECKING THE DISK TYPE.  IF THE SECTOR
;	IS VALID DATA CONTROL IS TRANSFERED TO
;	THE LOAD ADDRESS.
;
;
BOOT	LD	SP,SSTACK	;SET UP STACK POINTER
	IN	A,(7FH)
	LD	A,0
	LD	(UNIT),A	; SET UNIT BYTE TO 0 ;3.3 DKB
	LD	A,E		;*
	CP	4
	JP	NC,HDBIOS+3
	PUSH	AF	;*
	LD	A,0EFH		;STEP DRIVES AWAY FROM TRK 0
	PUSH	HL
	LD	(SPSV),SP
	POP	HL
BT1:	RRCA 			; SET UP DRIVE SELECT
	JR	NC,BT2
	OUT	(SELECT),A
	CALL	FRCINT
	AND	4
	JR	Z,BT3
	XOR	A
	OUT	(TRACK),A		;TELL CNTRLLR ITS AT 0
	LD	A,2
	LD	(TRK),A
	LD	A,1AH
	CALL	SEEK4
BT3:	IN	A,(SELECT)
	JR	BT1
BT2:	POP	AF	;*
	PUSH	AF		; 3.2
	CALL	HOME		; 3.2 OASIS MOD
	POP	AF		; 3.2
	CALL	UNITSL		;CHECK DISKETTE TYPE
	JR	NZ,GOMON
BT4:	CALL	BOOTLD		;LOAD IN BOOT LOADER
	LD	HL,COLD
	LD	A,(HL)		;LOOK FOR
	AND	0CEH		;CPM OR SDOS
	JR	NZ,BT5		;LOADER
	BIT	0,(HL)	
	JP	NZ,COLD		
BT5:	LD	A,COBYTE	;CHK FOR CAP SFTWRE
	LD	HL,COBSYS
	CP	(HL)
	JP	Z,COBSYS
GOMON:	LD	A,MNBYTE	;IF LOADR DIDN'T MAKE IT
	LD	HL,MNITR	;CHK 1ST BYTE OF MONITOR
	CP	(HL)		;IF IT'S THERE JUMP TO IT
	JP	Z,MONITR
HLT:	HALT 
BOOTLD	LD	HL,COLD		;COLD=BOOT LOAD ADDR
BOOT1	LD	(TADDR),HL
BOOT2	XOR	A
	LD	(TRK),A		;SET TO TRACK 0
	INC	A
	LD	(SCTR),A	;SET TO SECTOR 1
	CALL	READ		;READ BOOT SECTOR
	RET	Z		;RETURN IF NO ERROR
	JR	GOMON
CHGTYP:	LD	A,(UNIT)	;GET UNIT TYPE REGISTER
	LD	E,A		;STORE UNIT TYPE IN E
	LD	A,4		;IF ERROR CHECK DRIVE TYPE
	CP	B
	JR	Z,DD8256	;TRY DOUBLE DENSITY 8" 256 BYTE
	DEC	A		;IF NOT DD-8
	CP	B		;TRY SINGL DENSE 8"
	JR	Z,SD8
	DEC	A		;IF NOT SD8
	CP	B		;TRY SINGLE DENSITY 5"
	JR	Z,SD5-$
	DEC	A		;IT'S NOT SD-5
	CP	B		;TRY DOUBLE DENSITY 5"
	JR	Z,DD5-$
	OR	1		;MUST NOT BE ANY THING OUT
				;THERE SET ERROR FLAG
	POP	HL		;ADJUST RET ADDR
	RET			;AND RETURN
	EJECT
SD8	LD	A,E		;RECALL UNIT TYPE DATA
	RES	6,A		;RESET DOUBLE DENSITY BIT
	RES	7,A		;GET RID OF 256 BIT
	LD	(UNIT),A	;SET UNIT TYPE REGISTER
	RET	
DD8256:	LD	A,E		;UNIT DATA -> A
	SET	7,A		;SET 256 BYTE CNTRL BIT
	LD	(UNIT),A	;STUFF IT
	RET	
SD5	LD	A,E		;GET UNIT DATA
	SET	5,A		;RESET 8" SELECT BIT
	LD	(UNIT),A	;SET UNIT DATA
	RET	
DD5	LD	A,E		;GET UNIT DATA
	SET	6,A		;SET DOUBLE DENSITY BIT
	LD	(UNIT),A	;SET UNIT DATA
	RET	
	EJECT
;
;
;	THIS ROUTINE SETS UP THE UNIT BYTE FOR SYSTEM USE
;	TO INSTALL NEW DISKETTES OR DRIVES.
;
;
UNITSL	LD	B,4		;SET CTR FOR UNIT
				;SELECTION
	AND	0FH
	OR	40H
	LD	(UNIT),A	;SAVE UNIT NUMBER
	LD	HL,(TADDR)	;SAVE USER TADDDR
	LD	(TEMP2),HL
	CALL	USL1		;SET UNIT TYPE BITS
	LD	HL,(TEMP2)	;RECALL USER TADDR
	LD	(TADDR),HL
	LD	A,(UNIT)	;SAVE UNIT TYPE DATA
	RET	NZ		;RETURN IF ERROR FLG SET
	JR	NC,USL0
	SET	7,A
USL0:	LD	E,A
	LD	A,(SIDE)	;CHK DOUBL SIDE BIT
	OR	A
	LD	A,E		;RECALL UNIT TYPE DATA
	RES	4,A		;RESET DOUBLE SIDE BIT
	JP 	P,SS		;ALL SET IF SINGL SIDED
	SET	4,A		;SET DOUBLE SIDE BIT
SS	LD	(UNIT),A	;SET UNIT TYPE REGISTER
	XOR	A		;RESET ERROR FLAG
	RET			;RETURN TO CALLER
USL1:	PUSH	BC
	PUSH	IX
	PUSH	HL
	LD	(SPSV),SP
	POP	HL
	CALL	DRVSET
	CALL	IDRD
	POP	IX
	POP	BC
	LD	A,(IDSV+3)
	RRCA 
	RET	Z	
	DEC	B
	CALL	CHGTYP
	JR	USL1
	EJECT
;
;
;
;	DISK CONTROLLER LINKAGES
;
;
HOME	LD	(SPSV),SP
	PUSH	IX		;SAVE IX PTR
	CALL	DRVSET		; SELECT DRIVE
	CALL	HOME1		;RESTORE DRIVE
	POP	IX		;RESTORE IX
	RET	
;
;	SELECT DISK DRIVE
;
SELDSK	LD	A,C
	LD	(UNIT),A
	RET	
;
;	SET TRACK NUMBER
;
SETTRK	LD	A,C
	LD	(TRK),A
	RET	
;
;	SET SECTOR NUMBER
;
SETSEC	LD	A,C
	LD	(SCTR),A
	RET	
;
;	SET MEMORY TRANSFER ADDRESS FOR DISK READ/WRITE
;
SETDMA	LD	(TADDR),BC
	RET	
;
;	READ A SECTOR
;
READ	LD	BC,301H
READBT	LD	(RSEEK),BC	;SAVE NBR RETRYS
	PUSH	IX		;SAVE IX
	LD	IX,(IXSAV)	;SET CURRENT VARIABLE
				;TABLE
READ1	PUSH	BC
	CALL	RDSC		; READ A SECTOR
	POP	BC
	JR	Z,RWRET-$	; RETURN IF NO ERROR
	CALL	RETRY		; RETRY IF ERROR
	JR	READ1-$
RWRET:	POP	IX		;RESTORE IX
	RET			;RETURN TO CALLER
;
;	WRITE A SECTOR
;
WRITE	LD	BC,301H
WRBT:	LD	(RSEEK),BC	;SAVE NBR RETRYS
	PUSH	IX		;SAVE IX
	LD	IX,(IXSAV)	;SET CURRENT VARIABLE
				;TABLE
WRITE1:	PUSH	BC
	CALL	WRSC		; WRITE A SCTR
	POP	BC
	JR	Z,RWRET-$	; RETURN IF NO ERROR
	CALL	RETRY		; RETRY IF ERROR
	JR	WRITE1-$
	EJECT
;
;
;
RETRY:	DJNZ	RETRY2-$	;DO (B) RETRYS WITHOUT RESEEK
	LD	A,(RTRY)	;GET RETRY NUMBER
	LD	B,A
	DEC	C		;DO (C) RESEEKS
	JP 	P,RETRY1
	POP	AF
	POP	IX		;RESTORE IX IF ERROR
	XOR	A
	INC	A		; SET ERROR FLAG
	RET			; RETURN TO CALLER
RETRY1:	PUSH	BC
	CALL	HOME1		; RESTORE DRIVE
	POP	BC
RETRY2:	RET			; TRY AGAIN
HOME1:	LD	(SPSV),SP	;SET RET IF ERROR
	LD	A,(IX+RSCMD)	;RESTORE TO TRK 0
	CALL	SEEK4		;TYPE 1 COMMAND EXECUTION
	XOR	A		;RESET ERROR FLAG
	RET	
;
	EJECT
;
;
; CHECK DRIVE SEL AND CHANGE IF DIFFERENT
;
;
DRVSET:	LD	DE,UNIT		;GET ADDR OF UNIT TYP REG
	LD	A,(DE)		;PUT UNIT TYPE IN ACC
	AND	0E0H		;GET DRIVE TYPE BITS
	LD	C,A		;STORE DRIVE TYPE IN C
	LD	A,(DE)		;GET UNIT DATA
				;TO GET DRIVE NUMBER
	AND	03
	LD	B,A		;DRIVE NUMBER IN B
	LD	A,1		;IF DRIVE 0
	JR	Z,DRVSEL-$	;SET SELECT BIT 0
CKDRV1:	RLCA			;IF NOT SHIFT BIT TO
	DJNZ	CKDRV1-$	;PROPER POSITION
DRVSEL:	OR	C		;COMBINE DRIVE SELECT BITS
	AND	7FH
				;WITH DRIVE TYPE BITS
	LD	B,A		;STORE NEW SELECT DATA
	LD	A,C		;IF NOT CHANGE DRIVE TYPE
				;TABLE AND OUTPUT NEW 
				;SELECT DATA
	LD	IX,STDSDT	;DRIVE TYPE=8" SD
	CP	0
	JR	Z,CKDRV-$
	LD	IX,STDDDT	;DRIVE TYPE=8" DD
	CP	40H
	JR	Z,CKDRV-$
	LD	IX,DDT256
	CP	0C0H		;CHK FOR 256 BYTE OPTION
	JR	Z,CKDRV-$
	LD	IX,MINSDT	;DRIVE TYPE=5" SD
	CP	20H
	JR	Z,CKDRV-$
	LD	IX,MINDDT	;DRIVE TYPE=5" DD
CKDRV:	LD	(IXSAV),IX	;(IXSAV)=NEW TABLE ADDR
	PUSH	BC		;SAVE SELECT DATA
				;TO ENABLE DELAY
DRVST:	POP	AF		;GET SELECT DATA
	CPL 			;HRDWRE REG IS INVERTED
	OUT	(SELECT),A	;SET DRV SELECT REG
	LD	A,(DE)		; GET NEW DRIVE TYPE
	LD	(UNITCK),A	; SET OLD = NEW
	CALL	DELAY		; DRIVE SELECT DELAY
RDYCK:	IN	A,(STATUS)
	AND	80H
	JP	NZ,END2
	RET	
				;IF NOT AUTOMATIC RETURN
				;IN RDYCHK ROUTINE
	EJECT
;
;
;
;
;
; READ PRESENT DISK ADDRESS (TRK &SCTR)
;
;
IDRD:	CALL	WAIT		;FORCE NOT BUSY
	LD	HL,IDSV
	LD	BC,600H+DATA
	LD	A,0F8H
	LD	(ERMASK),A
	CALL	SWEB
	LD	A,RDACMD
	CALL	RDSC0	; READ ID
	LD	A,(IDSV)
	CP	77
	JP	NC,SEEK0
	OUT	(TRACK),A
	XOR	A
	RET	
;
;
DELAY	LD	A,(UNIT)
	BIT	5,A		;TEST MINI/FULL BIT
	LD	A,39		;32 MS DEL IF FULL
	JR	Z,DELAY1-$
	LD	A,60		;50 MS DEL IF MINI
DELAY1:	LD	B,0
	DJNZ	0
	DEC	A
	JR	NZ,DELAY1-$
	RET	
;
	EJECT
;
;
; READ SECTOR COMMAND
;
;
RDSC:	CALL	DRINIT
	LD	A,RDCMD		;READ COMMAND
	CALL	STSDBT
	LD	HL,(TADDR)	; SET TRANSFER ADDRESS
RDSC0	LD	(CMDSV),A
	LD	DE,(CMDSV)
	PUSH	DE
	DI			;DISABLE INT DURING TRX
	OUT	(CMD),A	; OUTPUT COMMAND
	JR	2
	JR	2	;WAIT FOR STATUS UPDATE
	INIR		; INPUT A SECTOR
	POP	DE
	LD	(CMDSV),DE
	EI		;RE ENABLE INTERRUPTS
	JR	END
;
;
STSDBT:
	LD	H,A	; SET UP SIDE BIT IN CMD
	LD	A,(SIDE)
	LD	L,A
	AND	1
	LD	A,H
	RET	Z	
	SET	1,A
	RET	
;
	EJECT
;	DRIVE INITIALIZATION ROUTINE
;
DRINIT:	POP	HL		;SET UP ERROR RETURN
	LD	(SPSV),SP
	PUSH	HL
	LD	A,(UNIT)	;GET DRIVE SELECT DATA
	LD	D,A
	LD	A,(UNITCK)	;GET PREVIOUS SELECT DATA
	CP	D		;SAME AS BEFORE?
	JR	Z,DINIT1-$		;IF SO,SKIP DRVSET
	CALL	DRVSET
	CALL	IDRD
DINIT1	CALL	SEEK
	LD	A,0FEH
	LD	(ERMASK),A
	JP	TRINT 
;
	EJECT
;
;
; WRITE SECTOR COMMAND
;
;
WRSC:	CALL	DRINIT
	LD	A,WRCMD
	CALL	STSDBT
	LD	HL,(TADDR)	;SET TRANSFER ADDRESS
	LD	(CMDSV),A
	DI			;DISABLE INTERRUPTS
				;DURING TRANSFER
	OUT	(CMD),A		; OUTPUT COMMAND
	JR	2
	JR	2		;WAIT FOR STATUS UPDATE
	OTIR  			; OUTPUT A SECTOR
	EI			;RE-ENABLE INTERRUPTS
;
;
;
; END OF COMMAND 
;
;
;
END	CALL	WAIT
	IN	A,(STATUS)
	LD	D,A
	LD	A,(ERMASK)
	AND	D	; CHECK FOR ERRORS
	RET	Z	
END1	LD	A,D
END2	LD	(ERSTAT),A	; SAVE ERROR BITS
	CALL	DELAY
	OR	1
	LD	SP,(SPSV)
	CALL	UNITFX		;FORCE DRVSET AFTER ERROR
	RET	
;
;
	EJECT
;
;
;  SEEK TRACK
;
SEEK	CALL	RDYCK
	LD	A,(IX+NTRKS)
	LD	C,A
	LD	A,(TRK)
	CP	C		;CHK FOR VALID TRK
	JR 	C,SEEK1-$
SEEK0:	LD	A,0FH
	JR	END2-$		; INVALID TRACK
SEEK1:	LD	C,A		; SAVE NEW TRK #
	IN	A,(TRACK)	; PRESENT TRACK
	CP	C
	RET	Z	; IF SAME TRK, RETURN
	LD	A,(IX+SKCMD)	; SEEK COMMAND
SEEK4:	LD	(CMDSV),A
	LD	B,210
	DJNZ	0
	CALL	WAIT
	LD	A,(TRK)
	OUT	(DATA),A
	LD	A,80H
	LD	(ERMASK),A
	LD	A,(CMDSV)
	OUT	(CMD),A
	LD	B,10
	DJNZ	0
	CALL	END
	CALL	DELAY
	LD	A,(CMDSV)
	CP	(IX+RSCMD)
	RET	Z	
	IN	A,(STATUS)
	AND	10H
	JR	NZ,SEEK2
	IN	A,(TRACK)
	CP	C
	RET	Z	
SEEK2:	LD	A,20H
END2JP:	JR	END2-$
	EJECT
;
;
;
WAIT:	LD	E,0
	PUSH	BC
	LD	C,2
WAIT2:	IN	A,(STATUS)
	AND	1
	JR	Z,DWAIT
	DJNZ	WAIT2-$
	DEC	E
	JR	NZ,WAIT2-$
	DEC	C
	JR	NZ,WAIT2
	POP	BC
	IN	A,(SELECT)
	OR	80H
	OUT	(RSET),A
	DJNZ	0		; RESET TO GET OUT OF WAIT
	IN	A,(RSET)
	CALL	FRCINT		;KILL AUTO RESTORE
	LD	A,(IX+RSCMD)	;& RESTORE @ PROPER STEP RATE
	CALL	SEEK4
	LD	A,0FEH		;ERSTAT=FE
	JR	END2JP		;FORCE RETRY
;
;
;		DISABLE WAIT STATES
;
;
DWAIT:	POP	BC
	IN	A,(SELECT)
	OR	80H	; NEG TRUE .AND.
			;RESETS WAIT ENABL BIT
	OUT	(SELECT),A
	RET	
;
;
; ENABLE WAIT STATES
;
;
SWEB	IN	A,(SELECT)
	AND	7FH	;NEG TRUE .OR.
			;SETS WAIT ENABL BIT
	OUT	(SELECT),A
	RET	
;
;
;
;
	EJECT
; INITIALIZE FOR DISK TRANSFER
;
;
TRINT:
	LD	B,0
	LD	A,(IX+NSCTRS)
	INC	A
	LD	C,A
	LD	A,(SCTR)
	CP	C		; CHECK FOR SIDE
	JR 	C,TRINT1-$
	LD	B,10H
	DEC	C
	SUB	C		; IF SIDE 2, SUBTRACT
TRINT1:	PUSH	AF
	CALL	CHGSID		; CHK SIDE AND CHG IF NEEDED
	POP	AF
	OUT	(SECTOR),A
TRINT2	LD	BC,.RES.(NBYTES*100H+DATA)
	LD	A,(UNIT)	; CHK 256 BYTE BIT
	RLCA
	JR	NC,SWEB
	LD	B,0		;IF SET, MAKE TRX LONGER
	JR	SWEB		; ENABLE WAIT STATES
;
CHGSID:	IN	A,(SELECT)
	CPL 
	LD	E,A		; CHECK SIDE SELECTED
	AND	10H
	CP	B
	RET	Z		; IF SAME SIDE, RET
	LD	A,E
	AND	6FH
	OR	B
	CPL 
	OUT	(SELECT),A	; SELECT NEW SIDE
	LD	B,210		;DELAY FOR SIDE CHANGE
TRINT3:	DJNZ	TRINT3
	JP	IDRD 	; SET UP SIDE BYTE
;
;
;	FORCE CHIP INTERRUPT COMMAND
;
;
FRCINT:	LD	A,0D0H
	OUT	(CMD),A	; 'FORCE INTERRUPT' CMD
	LD	A,10
FRC1:	DEC	A
	JR	NZ,FRC1
	IN	A,(STATUS)
	RET	
	EJECT
;
;
; LOAD # OF SECTORS IN (NREC)
;
;
LOADER	CALL	UNITFX		;FORCE DRIVE SETUP
LD1	CALL	READ		; READ A SECTOR
	RET	NZ
	CALL	INCP		; INC TRK/SCTR
	JR	NZ,LD1-$
	RET	
;
;
;
;
; SAVE # OF SECTORS IN (NREC)
;
;
SAVER	CALL	UNITFX		;FORCE DRIVE SETUP
SV1	CALL	WRITE
	RET	NZ
	CALL	INCP
	JR	NZ,SV1-$
	RET	
;
; INC SECTOR AND TRACK
;
;
INCP:
	LD	HL,(TADDR)
	LD	DE,NBYTES
	LD	A,(UNIT)	;CHK FOR 256 BYTE BIT
	RLCA
	JR	NC,INCP2
	LD	DE,NBYTES*2	; IF DD THEN MULT BY 2
INCP2:	ADD	HL,DE
	LD	(TADDR),HL
	LD	HL,NREC		; POINT TO NREC
	DEC	(HL)
	RET	Z	
	DEC	HL
	DEC	HL	; POINT TO SCTR
	INC	(HL)	; INC SCTR #
	LD	A,(IDSV+1)	; SET SIGN BIT IF 2 SIDES
	OR	A		; CLR CY ,CHK SIGN BIT
	PUSH	IX		; GET INDEX FOR CURRENT DISK
	LD	IX,(IXSAV)
	LD	A,(IX+NSCTRS)
	POP	IX
	JP 	P,INCP1
	RLCA		;IF DOUBLE SIDED,SHIFT LEFT
INCP1	INC	A
	CP	(HL)	; LAST SCTR ON TRK ?
	RET	NZ	; IF NOT, RETURN
	LD	(HL),1	; SET TO SCTR 1
	INC	HL	; POINT TO TRK
	INC	(HL)	; INC TRK #
	OR	A
	RET	
	EJECT
;
;
;************FORMAT CONTROLLER ROUTINE************
;
;	THIS ROUTINE WILL FORMAT A DISKETTE
;	ACCORDING TO THE DISK TYPE STORED IN
;	UNIT.
;
;
FMAT:	CALL	UNITFX		;FORCE DRIVE SETUP
	LD	(TEMP2),SP	;SAVE STACK PTR
	PUSH	IY		;SAVE IY INDEX PTR
	PUSH	IX
	PUSH	HL		
	LD	HL,800H		;SET UP IMAGE AREA
	LD	(TADDR),HL	;SET UP SPSV FOR
	LD	(SPSV),SP	;PROPER RETURN
	POP	HL		;ADDR.
	CALL	DRVSET		;SET UP UNIT SELECT REG
	CALL	Z,HOME1		;CONTINUE IF NO ERRORS
	JR	NZ,ERXIT-$	;EXIT IF ERROR
	CALL	SCTRIM	;MAKE SECTOR IMAGE IN RAM
	CALL	TRCKIM	;MAKE TRACK IMAGE IN RAM
			;SET H&L FOR SIDE DATA
	XOR	A		;CLR ACC
IDSET	CALL	SETID		;SET SECTOR &TRK ID
	PUSH	BC
	CALL	FMAT1		;FORMAT 1 TRACK
	CALL	NXTRK		;IF DOUBLE SIDED
	POP	BC
				;DO BOTH SIDES
	JR	NZ,FINISH-$	;QUIT IF ERROR
	CP	(IX+NTRKS)	;CHK TRK NBR
	JR	NZ,IDSET-$	;FORMAT NXT TRK
				;IF NOT FINISHED
FINISH:	LD	A,76
	LD	(TRK),A		;PUTTING 76 HERE ALLOWS
				;MONITOR Z COMMAND TO WORK
	IN	A,(SELECT)	;FIX BIT 5 SO MONITOR
	RES	5,A		;THINKS THE DRIVE IS 
	OUT	(SELECT),A	;SINGLE SIDED
	LD	DE,UNITCK
	LD	A,(DE)		;FIX UNITCK TO REFLECT
	SET	5,A		;CHANGE IN SELECT
	LD	(DE),A		;REGISTER
	POP	IX
	POP	IY	;RESTORE INDEX REGISTERS
	RET	
;
;
;	UPON LEAVING THIS ROUTINE THE FOLLOWING REGISTER
;		INFORMATION IS AVAILABLE:
;
;		(IXSAV) = ADDR OF TABLE OF VARIABLES
;				FOR THE DISK TYPE
;		A       = 77
;		BC      = NUMBER OF BYTES PER SECTOR
;		DE      = ADDR OF 1ST BYTE OF LAST SECTOR
;		H       = NUMBER OF SIDES FORMATED
;		L       = MSB SET IF DOUBLE SIDED
;		A'      = FILL CHARACTER
;		B'      = 0
;		DE'     = ADDR OF 1ST ID FIELD
;		HL'     = HL
;
;
ERXIT	POP	IX
	LD	SP,(TEMP2)	;ERROR RETURN
	RET	
	EJECT
;
;
;
;************SECTOR IMAGE CONTROLLER ROUTINE************
;
;
;
;	ASSUMES: IX = PTR TO TABLE OF DISK TYPE VARIABLES
;		 TADDR = BUFFER SPACE TO BE USED FOR TRACK
;			 IMAGE
;
;
SCTRIM:	LD	HL,(TADDR)	;SET IMAGE BUFFER PTR
	LD	A,(IX+GAP2)	;CHECK FOR DD OR SD
	RRCA 			;IF LSB OF GAP =0
	LD	A,4EH		;FORMAT IS DOUBLE DENSITY
	JP	NC,HEADER	;DD FILL CHAR = 4E
	LD	A,0FFH		;SD FILL CHAR = FF
HEADER	LD	E,A		;STORE FILL CHAR IN E
	LD	B,(IX+HEADR)	;HEADR = NBR OF FILL CHARS
	CALL	IMBLD		;IN FRONT OF ALL '0' SYNC
	LD	B,(IX+GAP3)
	CALL	IMBLD
	XOR	A		;SYNC CHAR IN A
	LD	B,(IX+GAP1)	;GAP1 = NBR OF SYNC CHARS
	CALL	IMBLD
	CALL	MRKCHK		;IF DD SPECIAL MARK REQD
IDMARK:	LD	A,0FEH		;ID MARK IN ACC
	LD	(HL),A		;PUT ID MRK IN BUFFR
	INC	HL
	PUSH	HL		;STORE BFFR LOC OF ID
	EXX
	POP	DE		;IN DE'
	EXX
	XOR	A
	LD	B,4		;4 BLANK LOCATIONS FOR ID
	CALL	IMBLD
	LD	A,0F7H		;SENDING AN F7 CAUSES
	LD	(HL),A		;2 CRC BYTES FOR ID
	INC	HL
	LD	B,(IX+GAP2)	;GAP2=NBR OF PRE-DATA
				;SYNC FILL CHARACTERS
	LD	A,B
	SRL	A
	INC	A
	LD	C,A		;TEMP1=NBR OF PREDATA
	LD	A,E		;SYNC CHARS
	CALL	IMBLD
	LD	B,C
	XOR	A
	CALL	IMBLD		;WRITE PRE DATA SYNC
	CALL	MRKCHK		;IF DD SPECIAL MRK REQD
	LD	A,0FBH		;WRITE DATA MARK
	LD	(HL),A
	INC	HL
	LD	B,128		;WRITE DATA=128 BYTES
	LD	A,(UNIT)	;CHK 256 BYTE BIT
	RLCA
	JR	NC,IDM
	LD	B,0		;IF SET MAKE DATA AREA 256
IDM:	LD	A,0E5H		;FORMAT DATA=E5
	CALL	IMBLD
	LD	A,0F7H		;WRITE CRC
	LD	(HL),A
	INC	HL
	RET	
;
;	REGISTERS ARE SET AS FOLLOWS UPON
;	EXIT FROM SCTRIM:
;	IX	=DISK VARIABLE TABLE ADDR
;	A	=F7
;	B	=0
;	C	=NUMBER OF DATA SYNC CHARACTERS (0'S)
;	HL	=CURRENT BYTE IN IMAGE BUFFER PTR
;	DE'	=ADDR OF 1ST BYTE OF ID (1ST SECTOR)
;	REMAINING REGISTERS NOT USED IN THIS ROUTINE
;
;
;
;::::::SPECIAL ID MARK LOADED IF NEEDED::::::
;
MRKCHK:	LD	A,E
	OR	A		;CHK SIGN BIT
	RET	M		;MINUS SIGN NOT SET
	LD	A,0F5H		;IF SPECIAL ID REQUIRED
	LD	B,3		;3 CHARACTERS NEEDED
;
;
;
;
;
;::::::DATA BLOCK LOADER::::::
;
;	ASSUMES:	BC=NUMBER OF LOADS
;			HL=PTR TO LOAD ADDR
;			A =DATA TO BE LOADED
;
IMBLD:	LD	(HL),A	;PUT THE BYTE IN A INTO
	INC	HL	;THE BUFFER
	DJNZ	-2	;IF B=0 RETURN
	RET	
	EJECT
;
;************TRACK IMAGE CONTROLLER ROUTINE************
;
;	ASSUMES:
;		DE'	= 1ST BYTE OF ID IN SECTOR
;			  IMAGE
;		HL	= BUFFER PTR TO CURRENT BYTE
;		IX	= ADDR OF DISK VARIABLE TABLE
;
;
TRCKIM:	EXX
	LD	B,(IX+NSCTRS)	;BC'=NBR OF SECTORS
	DEC	B
	EXX
	LD	DE,(TADDR)	;POINT DE TO 1ST BYTE
	PUSH	HL		;HL POINTS TO 1ST BYTE
				;OF 2ND SECTOR
	OR	A		;CLR CY FLAG
	LD	C,(IX+HEADR)	;DONT REPEAT HEADER
	LD	B,0
	EX	DE,HL	
	ADD	HL,BC
	EX	DE,HL	
	SBC	HL,DE		;HL-DE=NBR BYTES/SCTR
	PUSH	HL
	POP	BC		;HL-->BC
	POP	HL		;CURRENT BFFR LOC IN HL
	PUSH	BC		;STORE NBR BYTES/SCTR
	EX	DE,HL		;SET BUFFER PTRS
	EXX
BLDTRK	EXX
	LDIR			;BUILD A SECTOR
	POP	BC		;RECALL NBR BYTES/SCTR
	PUSH	BC
	EXX
	DJNZ	BLDTRK		;REPEAT UNTIL ALL
	EXX			;SECTORS LOADED
	POP	BC		;RESTORE NBR BYTES PER
				;SECTOR
;
;	REGISTERS ARE SET UP AS FOLLOWS UPON EXIT
;	FROM TRCKIM:
;
;	IX	= ADDR OF DISK VARIABLE TABLE
;	A	= F7
;	BC	= NUMBER OF BYTES PER SECTOR
;	DE	= ADDR OF 1ST BYTE  PAST LAST SECTOR
;	HL	= ADDR OF 1ST BYTE OF LAST SECTOR
;	B'	= 0
;	DE'	= ADDR OF ID OF 1ST SECTOR
;
;
	EJECT
;
;
;+++++++++SIDE SELECT ROUTINES FOR FORMAT CONTROLLER+++++++++
;
;
;	THIS ROUTINE SETS THE H & L REGISTERS
;	TO INDICATE SIDE STATUS.
;
;
SIDECK:	EX	DE,HL		;GET FILL CHARACTER
	LD	A,(UNIT)	;GET DISK TYPE BYTE
	BIT	4,A		;CHK DBLE SIDE BIT
	LD	A,80H		;SET DOUBLE SIDE FLAG
	JR	NZ,SCHK1	;IF BIT 4 SET IN UNIT
	XOR	A		;CLR DS FLAG IF NOT SET
SCHK1	LD	L,A		;SET UP L AS FLAG REG
	LD	H,L		;H=SIDE#,+SIDE FLG
	RET	
	EJECT
;
;************SECTOR ID CONTROLLER ROUTINE************
;
;
;	ASSUMES:
;		A	= TRACK NUMBER
;		BC	= NUMBER OF BYTES PER SECTOR
;		H	= SIDE NUMBER
;		L	= MSB SET IF DOUBLE SIDED
;		DE'	= ADDR OF 1ST SECTOR ID
;		IX	= ADDR OF DISK VARIABLE TABLE
;
SETID:	PUSH	HL
	PUSH	BC
	EXX
	POP	BC		;GET NBR BYTES / SCTR
	POP	HL		;HL-->HL'
	PUSH	DE		;PUT 1ST SECTR ID ADDR
	POP	IY		;IN IY
	PUSH	DE		;SAVE 1ST ID ADDR
	EX	AF,AF'	
	LD	D,1		;SECTOR NUMBER
	LD	A,(IX+NSCTRS)	;A'=NBR OF SECTRS
	CP	26		;IF 26 SECTORS,STANDARD
	LD	A,1		;FORMAT IS USED (8"-SD)
	JR	Z,ID1-$
	LD	A,(IX+NSCTRS)	;IF NOT ALTERNATE
				;SECTOR NUMBERS
	SRL	A		;IF EVEN NBR OF
				;SECTORS,SCTR 1
				;IS 1ST
	INC	A		;IF ODD NBR SCTRS
				;NSCTRS/2)+1 IS 1ST
	JR	NC,ID2-$	;IF CY=1 ODD # SCTRS
ID1	EX	AF,AF'	
	LD	(IY),A		;SET TRACK NBR
	OR	L		;SET SIDE BYTE
	JP 	P,ID1A		;IF DOUBLE SIDED
	LD	(IY+1),H
	RES	7,A		;CLR BIT SET IN A
ID1A	EX	AF,AF'	
	LD	(IY+2),A	;SET SECTOR NUMBER
	PUSH	AF
	LD	A,(UNIT)	;CHK 256 BYTE BIT
	RLCA
	JR	NC,ID4
	LD	A,1
	LD	(IY+3),A
ID4:	POP	AF
	CP	(IX+NSCTRS)	;ALL SCTRS DONE
	JR	Z,ID3-$		;IF SO RETURN
	ADD	IY,BC		;IF NOT DO NXT SCTR
	INC	A
	EJECT
ID2	LD	E,A		;IF 8" SD ,SECTORS ARE
	LD	A,26		;SEQUENTIAL.  IF NOT
	CP	(IX+NSCTRS)	;LOWER HALF ALTERNATES
	LD	A,E		;WITH UPPER HALF
	JR	Z,ID1-$		;IF Z=1 DON'T ALTERNATE
	LD	A,D		;IF Z=0 ALTERNATE
	LD	D,E
	JR	ID1-$
ID3	EX	AF,AF'		;RETRN ALT REG SET
	POP	DE
	EXX
	RET			;AND RETURN
;
;
;	REGISTERS ARE SET AS FOLLOWS UPON EXIT FROM
;	IDSET:
;
;	IX	= ADDR OF DISK VARIABLE TABLE
;	IY	= ID ADDR OF LAST SECTOR
;	A	= TRACK NUMBER
;	BC	= NUMBER OF BYTES PER SECTOR
;	DE	= 1ST BYTE OF LAST SECTOR (ADDR)
;	H	= SIDE NUMBER
;	L	= MSB SET IF DOUBLE SIDED
;	B'	= 0
;	DE'	= ADDR OF 1ST ID
;	HL'	= HL
;
	EJECT
;
;
;************DISK FORMAT WRITE CONTROLLER************
;
;
;	ASSUMES:
;		A'	= LAST SECTOR NUMBER
;		BC	= NUMBER BYTES PER SECTOR
;		(DE)	= 1ST BYTE OF LAST SECTOR
;		(TADDR)	= BEGINNING OF BUFFER
;
;
FMAT1:	PUSH	DE		;PUT LOC OF FILL CHARCTR
				;ON STACK
	PUSH	BC		;PUT NBR BYTES/SCTR ON STK
	EXX			;GET AUX REG SET
	EX	AF,AF'
	POP	BC
	PUSH	DE
	LD	E,A		;E'=NBR SCTRS/TRK
				;C'= NBR BYTES/SCTR
	LD	D,C
	LD	B,(IX+HEADR)		;D'=C' B'= # HEADR BYTES
	LD	C,DATA		;C'= DISK DATA PORT ADDR
	LD	HL,(TADDR)	;(HL')=LOC OF DATA TRX BFFR
	LD	A,80H		;CHK READY BIT
	LD	(ERMASK),A
	CALL	SWEB		;ENABLE WAIT STATES
	LD	A,(UNIT)	;CHK 256 BYTE BIT
	RLCA
	LD	A,0
	JR	NC,FMAT3
	LD	A,1		;IF SET INCREASE OUTPUT BY 256
FMAT3:	LD	(TEMP1),A
	LD	A,WRTCMD	;SET UP WRT TRK CMD
	LD	(CMDSV),A
	DI			;DISABLE INTERUPTS
				;DURING TRANSFERS
	OUT	(CMD),A
	LD	A,(TEMP1)
	OTIR  			;OUTPUT HEADER
	LD	B,D		;LOAD DATA CTR FOR 1ST SCTR
FMAT5:	OTIR  			;OUTPUT DATA TO DISK
	OR	A
	JR	Z,FMAT4
	OTIR  			;IF 256 BYTES OUT ANOTHR 256
FMAT4:	LD	B,D		;RELOAD DATA CTR FOR NXT SCTR
	DEC	E		;DECRMNT SCTR CTR
	JR	NZ,FMAT5	;WRITE NXT SECTOR UNTIL
				;ALL DONE
;
;	THE ABOVE PORTION OF THE WRITE CONTROLLER
;	CREATES NSCTRS ON THE DISK.
;
	EJECT
;
;	THE NXT SECTION CREATES THE GAP4 TRAILER
;
	POP	DE
	POP	HL		;POINT HL TO FILL CHAR
	LD	A,(HL)		;PUT FILL CHAR IN A
	OUT	(C),A 		;GAP4 =FILL CHAR TO INDEX
				;MARK
	DJNZ	-2
	EI			;RE-ENABLE INTERRUPTS
	EXX
	EX	AF,AF'		;RECALL NORMAL REG SET
	RET			;RETURN TO CALLER
;
;
;	THE REGISTERS ARE SET AS FOLLOWS UPON EXIT 
;	FROM FMAT1:
;
;	(IX)	= DISK  VARIABLE TABLE
;	(IY)	= ID OF LAST SECTOR
;	A	= TRACK NUMBER
;	BC	= NUMBER BYTES/SECTOR
;	(DE)	= 1ST BYTE OF LAST SECTOR
;	H	= SIDE NUMBER +80H IF 2 SIDES
;	L	= 80H IF DOUBLE SIDED 0 IF NOT
;	A'	= FILL CHARACTER
;	B'	= 0
;	(C')	= DISK DATA PORT
;	(DE')	= UNCHANGED
;	(HL')	= (DE)
;
	EJECT
;
;
;	THIS ROUTINE DECIDES WHETHER TO INCREMENT
;	THE TRACK NUMBER OR TO CHANGE SIDES WHEN
;	LOOKING FOR THE NEXT TRACK
;
NXTRK:	EX	AF,AF'	
	LD	A,47		;DELAY FOR TRACK CHANGE
DEL1:	DJNZ	0
	DEC	A
	JR	NZ,DEL1-$
	IN	A,(SELECT)	;GET HRDWRE SELECT REG
	OR	80H		;GET RID OF MSB(NEG LOG)
	BIT	7,L		;CHK SIDE BIT
	JR	Z,INCTRK-$	;SKP SIDE CHG IF 1 SIDED
	BIT	0,H		;CHECK SIDE
	RES	0,H
	JR	NZ,INCTRK-$	;IF PREV SIDE = 2 INC TRK
	INC	H		;IF PREV SIDE =1,
				;SET TO SIDE 2
	RES	4,A		;(NEG LOG BIT SET)
	OUT	(SELECT),A	;SET SIDE 2 IN HRDWRE
	DJNZ	0
	EX	AF,AF'	
	CP	A		;SET Z BIT
	RET	
	EJECT
INCTRK	SET	4,A		;NEG LOG RESET
	OUT	(SELECT),A	;SET HRDWRE TO SIDE 1
	EX	AF,AF'		;GET TRACK NUMBR
	INC	A		;NXT TRK NBR
	CP	(IX+NTRKS)	;LAST TRACK?
	RET	Z		;IF SO STOP
	LD	(TRK),A		;SAVE TRACK NUMBER
	PUSH	HL		;STORE ERROR RET
	LD	(SPSV),SP
	POP	HL
	DJNZ	0		;SIDE CHG DELAY
	EXX
	EX	DE,HL		;DONT DESTROY REGISTERS
	LD	A,(IX+SKNCMD)	;NO VERIFY SEEK
	CALL	SEEK4		;DO SEEK
	EX	DE,HL		;RESTORE REGISTERS
	EXX
	IN	A,(TRACK)		;GET CURRENT TRACK NBR
	LD	B,A
	LD	A,(TRK)
	CP	B
	LD	B,0
	RET	
	EJECT
