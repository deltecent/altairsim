DIAG	XOR	A
	LD	(TRK),A
	INC	A
	LD	(SCTR),A
	JR	DIAG1
DIA10	LD	HL,BFFR1
	LD	(TADDR),HL
	CALL	WRE
	CALL	NZ,ERROR
DIA11	LD	HL,BFFR2
	LD	(TADDR),HL
	CALL	RDE
	CALL	NZ,ERROR
	LD	A,(RQST)
	CP	2
	JR 	Z,DIAG3
	PUSH	AF
	CALL	COMPR
	POP	AF
	CP	3
	JP 	Z,RINCR
	CP	4
	JP 	Z,DINCR
DIAG3	LD	HL,SCTR
	INC	(HL)	; INC SECTOR
	LD	A,(IX+NSCTRS)
	PUSH	HL
	LD	HL,UNIT
	BIT	4,(HL)
	POP	HL
	JR 	Z,SS1
	RLCA
SS1	INC	A
	CP	(HL)
	JR	NZ,DIAG1 ; IF NOT END OF TRK, JMP
	LD	(HL),1	; SET TO SCTR 1
	INC	HL	; POINT TO TRK
	INC	(HL)	; INC TRK #
DIAG4	LD	A,(IX+NTRKS)
	CP	(HL)
	JR	NZ,DIAG1
	LD	(HL),0	; SET TO TRK 00
	LD	C,'P'
	CALL	COE	; PRINT 'P' EVERY COMPLETE PASS
DIAG1	CALL	CSE
	JR 	Z,DIAG2
	CALL	CIE
	CP	'.'
	RET	Z
DIAG2	LD	A,(RQST)
	CP	2
	JR	Z,DIA11
	JR	DIA10
;
;
;
COMPR:	LD	HL,BFFR2
	EX	DE,HL	
	LD	HL,BFFR1
	LD	A,(UNIT)
	RLCA
	LD	B,80H
	JR	NC,CMPR1
	LD	B,0
CMPR1	LD	A,(DE)
	CP	(HL)
	LD	A,0FFH
	LD	(ERSTAT),A
	JP	NZ,ERROR
	INC	HL
	INC	DE
	DJNZ	CMPR1
;
;
;
;
;
;
;
INCRD	LD	HL,RANDS
	LD	DE,BFFR1
	LD	B,NBYTES/2
	LD	A,(UNIT)
	RLCA
	JR	C,IR1
	SLA	B
IR1:	LD	A,(HL)
	RRCA
	JR 	C,HERE
	INC	DE
HERE	LD	A,R	
	LD	(DE),A
	INC	DE
	INC	DE
	DJNZ	HERE
	LD	A,(HL)
	RRCA
	JR 	C,SKIP
	INC	A
	LD	(HL),A
	RET	
SKIP	XOR	A
	LD	(HL),A
	RET	
;
;
;
DINCR:	PUSH	HL
	LD	HL,UNIT
	LD	A,(HL)
	AND	0F0H
	LD	(HL),A
	LD	A,R
	NOP
	AND	1
	OR	(HL)
	LD	(HL),A		;RANDOM UNIT
	POP	HL
RINCR:	LD	A,(IX+NSCTRS)
	INC	A
	LD	B,A
	LD	A,R
	AND	01FH
	OR	A
	JR	Z,RINCR		;SECTOR 0 ILLEGAL
	LD	(SCTR),A
	CP	B
	JR	NC,RINCR	;IF NO>NSCTRS TRY AGAIN
ONCM	LD	A,(IX+NTRKS)
	LD	B,A
	LD	A,R
	AND	07FH
	LD	(TRK),A
	CP	B
	JR	NC,ONCM		;IF NO>NTRKS TRY AGAIN
	JP	DIAG1 
;
;
;
;
TSTSK	CALL	HME
	LD	A,(IX+NTRKS)
	DEC	A
	OUT	(DATA),A
	LD	A,(IX+SKNCMD)	; SEEK (NO VERIFY)
	OUT	(CMD),A
	CALL	CSE
	JR	Z,TSTSK
	CALL	CIE
	CP	'.'
	RET	Z
	JR	TSTSK
;
;
;
;
;
;
PACSPC:	CALL	PACC
	LD	C,' '
	JP	COE 
;
;
;
;	FORCE DRIVE SETUP
;
UNITFX:	LD	A,0FFH
	LD	(UNITCK),A	;MAKE UNITCK NOT EQ TO UNIT
ZEND:	RET	
	EJECT
