	TITLE	SDOS-COSMOS FLOPPY CONTROLLER
	NAME	DDB200
;
;	FLOPPY DISK DRIVER FOR SDOS-COSMOS
;
;		BY	REX BROWN
;
;	VERSION	3.1	5/10/80
;			8/13/80	SPLIT DDBIOS FOR SD100/200
;		3.2	8/13/81	TRK 0 DTYPE ON BOOT FOR OASIS...DKB
;		3.3	6/24/82	SET UNIT BYTE TO ZERO FOR BOOT UP..DKB
;
;	RUNS ON SD200/700 SYSTEMS
;
;
