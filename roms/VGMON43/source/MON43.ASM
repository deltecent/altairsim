;  VECTOR MZ MONITOR 4.3, converted from the printed listing to M80 source.
;
;  Assemble and link with M80 and L80:
;
;	M80 MON43,MON43=MON43.ASM
;	L80 /P:E000,MON43,MON43/N/X/E
;
;  L80 asks "Origin above loader memory" twice. Answer Y, which writes
;  MON43.HEX, then N, which returns to CP/M.
;
;  Changes from the listing, made because M80 needs them. The object
;  code is the same:
;	RET, PAGE, HEXRULER	renamed VRET, VPAGE, HEXRLR
;	DTH, DT			written as DC, DB
;	PUSH IX, PUSH IY	written as DB
;	*			comment lines start with ;*
;	LINK			kept as a comment
;	ORG BASE		written as .PHASE BASE, L80 /P sets the origin
;	ORG MSEND		kept as a comment
;	ORG and DS above ROM	written as EQU, so nothing lands in RAM
;	ORG KTABL+30		written as DS with a zero fill
;	E7EF-E7FF		added at the end, from the ROM
;	strict left-to-right expressions rewritten with HIGH, LOW, ()
;
	.8080
;
;  The listing's Z-80 instructions, as macros
;
JR	MACRO	ADDR
	DB	18H
	DB	ADDR-$-1
	ENDM
JRNZ	MACRO	ADDR
	DB	20H
	DB	ADDR-$-1
	ENDM
JRZ	MACRO	ADDR
	DB	28H
	DB	ADDR-$-1
	ENDM
JRNC	MACRO	ADDR
	DB	30H
	DB	ADDR-$-1
	ENDM
JRC	MACRO	ADDR
	DB	38H
	DB	ADDR-$-1
	ENDM
LDED	MACRO	ADDR
	DB	0EDH,5BH
	DW	ADDR
	ENDM
SDED	MACRO	ADDR
	DB	0EDH,53H
	DW	ADDR
	ENDM
SBCD	MACRO	ADDR
	DB	0EDH,43H
	DW	ADDR
	ENDM
LDI	MACRO
	DB	0EDH,0A0H
	ENDM
LDIR	MACRO
	DB	0EDH,0B0H
	ENDM
CCI	MACRO
	DB	0EDH,0A1H
	ENDM
OUTI	MACRO
	DB	0EDH,0A3H
	ENDM
EXAF	MACRO
	DB	08H
	ENDM
EXX	MACRO
	DB	0D9H
	ENDM
INP	MACRO	R
	DB	0EDH,40H+(R*8)
	ENDM
OUTP	MACRO	R
	DB	0EDH,41H+(R*8)
	ENDM
DD	MACRO	V
	DB	HIGH (V)
	DB	LOW (V)
	ENDM
