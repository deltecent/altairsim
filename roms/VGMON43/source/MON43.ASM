CONS	EQU	0			;CONS STATUS PRT
COND	EQU	1			;CONS DATA PORT
RDA	EQU	40H			;RECEIVE FLAG
STPOL	EQU	0			;STATUS POLARITY
SPTR	EQU	PR+01FD0H		;STACK POINTER
DSBOOT	EQU	0E800H			;DUALSTOR BOOTSTRAP
MSBOOT	EQU	0E802H			;MEGASTOR BOOTSTRAP
FLBOOT	EQU	0E80CH			;FLOPPY BOOTSTRAP
DBUSY	EQU	0FF10H			;CONTROLLER BUSY
;*
;****************** COMMAND FORMAT *******************
;*   A SSSS FFFF ASCII DUMP OF MEMORY                  *
;*   B JUMP TO BOOTSTRAP LOADER                        *
;*   C SSSS FFFF CCCC COMPARE BLOCKS                   *
;*   D SSSS FFFF DUMP MEMORY IN HEX & ASCII            *
;*   E EXTERNAL COMMUNICATIONS                         *
;*   F SSSS FFFF DD DD TWO BYTE SEARCH                 *
;*   G SSSS GO TO AND EXECUTE                          *
;*   H JUMP TO HIGH RAM AT FC00                        *
;*   I PP INPUT FROM PORT                              *
;*   J JUMP TO DOS                                     *
;*   K LLLL SET A BREAKPOINT                           *
;*   L JUMP TO LOW RAM AT 0                            *
;*   M SSSS FFFF DDDD MOVE BLOCK                       *
;*   N NON DESTRUCTIVE MEMORY TEST                     *
;*   O PP DD OUTPUT TO PORT                            *
;*   P LLLL PROGRAM MEMORY                             *
;*   Q SSSS FFFF COMPUTE CHECKSUM                      *
;*   R DUMP Z-80 REGISTERS                             *
;*   S SSSS FFFF DD SEARCH FOR SINGLE BYTE             *
;*   T SSSS FFFF TEST MEMORY                           *
;*   U JUMP TO USER AREA AT 100H                       *
;*   V BOOT FROM 8 INCH DISK                           *
;*   W BOOT WINCHESTER DISK                            *
;*   X SSSS FFFF DDDD EXCHANGE BLOCK                   *
;*   Y KEYBOARD ECHO                                   *
;*   Z SSSS FFFF DD ZERO OR FILL MEMORY                *
;*******************************************************
;*
	.PHASE	BASE
;* JUMP TABLE OF ENTRY POINTS
MONIT:	JMP	INIT			;INITIALIZE ALL
KEYTST:	JMP	KEYSTAT			;TEST KEYBOARD
KEYDATA:	JMP	CONVERT			;INPUT KEYBOARD
CRT:	JMP	VIDEO			;OUTPUT TO SCREEN
ESC:	JMP	ESCAPE			;KEYBOARD INPUT
;*
;* TABLE OF COMMANDS FOR USART
INITABLE:	DB	0,0,0,40H,0CEH,27H
;*
INIT:	LXI	SP,SPTR			;INIT STACK
	CALL	ESCAPE			;DUMP LATCH
	XRA	A
	STA	XYFLAG
	STA	DBUSY			;CLEAR CONTROLLER FLAG
;* INITIALIZE USARTS AT PORTS 3,5,7
	MVI	A,3			;STARTING PORT
	MOV	C,A
INILOOP:	MVI	B,6			;NO OF COMMANDS
	LXI	H,INITABLE
OUTLOOP:	OUTI				;OUTPUT A BYTE
	XTHL				;DELAY FOR 6 MHZ.
	XTHL
	JRNZ	OUTLOOP			;SEND NEXT BYTE
	INR	C
	INR	C
	DCR	A			;DO 3 PORTS IN ALL
	JRNZ	INILOOP
;* PATCH RST 7
	MVI	A,0C3H			;JUMP
	STA	38H			;RST 7
	LXI	H,DUMPREGS
;* DISPLAY SIGN ON
	CALL	SIGN
;* CLEAR BREAKPOINT
CLRBRK:	LHLD	BKPTLOC
	LXI	D,BRKCODE
	SDED	BKPTLOC
	LDAX	D
	MOV	M,A
START:	LXI	SP,SPTR			;INITIALIZE STACK
	LXI	H,VPAGE			;FULL SCREEN SCROLL
	SHLD	TOSCN
	CALL	PROMPT
KEYPOL:	CALL	ESCAPE			;READ KEYBOARD
	JRZ	KEYPOL
	ANI	5FH			;UPPER AND LOWER
	LXI	H,START
	PUSH	H
	CPI	'D'-64
	CZ	VIDEO			;ECHO CLEARSCN
	CPI	'A'
	RC				;TOO SMALL
	CPI	05BH
	RNC				;TOO LARGE
	LXI	H,CMDTB+7EH
	PUSH	PSW
	ADD	A
	ADD	L
	MOV	L,A
	MOV	E,M
	INX	H
	MOV	D,M
	XCHG
	POP	PSW
	PCHL				;AWAY WE GO
;* COMMAND TABLE
CMDTB:	DW	WASCII			;A
	DW	FLBOOT			;B
	DW	COMPR			;C
	DW	HEXRUL			;D
	DW	EXTCOM			;E
	DW	FIND			;F
	DW	EXEC			;G
	DW	RAM			;H
	DW	PINPT			;I
	DW	WARM			;J
	DW	SETBRK			;K
	DW	LORAM			;L
	DW	MOVEB			;M
	DW	NDMT			;N
	DW	POUTP			;O
	DW	PROGRAM			;P
	DW	CHKSM			;Q
	DW	DREGS			;R
	DW	SRCH			;S
	DW	TMEM			;T
	DW	USER			;U
	DW	DSBOOT			;V
	DW	MSBOOT			;W
	DW	EXCHG			;X
	DW	ECHO			;Y
	DW	ZEROM			;Z
;*
;*** EXECUTE THE PROGRAM AT THE ADDRESS ***
;*
EXEC:	CALL	PTSTNG
	DC	'GO TO '
	CALL	AHEX			;READ ADD FROM KB
	XCHG
	PCHL				;JUMP TO IT
;*
;*** CONVERT UP TO 4 HEX DIGITS TO BIN
;*
AHEX:	MVI	C,4			;COUNT OF 4 DIGITS
AHE0:	LXI	H,0			;16 BIT ZERO
AHE1:	CALL	ESCAPE
	CPI	' '			;SPACE?
	JZ	SPCOVR
	CALL	HEX			;CHECK VALUE
	JRC	AHE1
	DAD	H			;MULT H*16
	DAD	H
	DAD	H
	DAD	H
	ADD	L
	MOV	L,A
	DCR	C			;4 DIGITS?
	JNZ	AHE1			;KEEP READING
	XCHG
SPCE:	MVI	A,20H			;PRINT SPACE
PTCN:	JMP	VIDEO
CRLF:	MVI	A,0DH			;PRINT CR
	CALL	PTCN
	MVI	A,0AH
	JR	PTCN
;*
SPCOVR:	CALL	VIDEO
	JR	SPCE-1
;*
;* CHECK FOR HEX VALUE, CONVERT
HEX:	CPI	30H			;<0
	RC
	CPI	':'			;>9
	JRC	NUM
	ANI	5FH			;UPPER & LOWER CASE
	CPI	'A'			;<A
	RC
	CPI	'G'			;>F
	CMC
	RC
NUM:	CALL	VIDEO
	SUI	48			;ASCII BIAS
	CPI	10			;DIGIT 0-10
	JRC	ALFA
	SUI	7			;ALPHA BIAS
ALFA:	ANA	A			;CLEAR CY
	RET				;WITH CY CLEAR
;*
;* READ 2 DIGITS FROM THE CONSOLE
AHE2:	MVI	C,2
	JR	AHE0
;*
;* SHORT ROUTINE TO SAVE CODE
TAHEX:	CALL	AHEX
	JR	AHEX
;*
;*** READ FROM CONSOLE TO REG A ***
;*
RDCN:	CALL	ESCAPE			;READ KEYBOARD
	JRZ	RDCN
	CPI	60H
	JRC	PTCN
	ANI	5FH
	JR	PTCN
;*
PAUSE:	CALL	ESCAPE
	CPI	20H
	RNZ
PLOOP:	CALL	ESCAPE
	CPI	20H
	JNZ	PLOOP
	RET
;*
ESCAPE:	CALL	KEYSTAT
	RZ
	CALL	CONVERT
	CPI	1BH			;ESCAPE
	JZ	START
	RET
;*
KEYSTAT:	IN	CONS
	ANI	RDA
	RET
;*
;* KEYBOARD CODE CONVERSION
CONVERT:	IN	COND			;KEYBOARD DATA
	PUSH	H
	PUSH	B
	LXI	B,(TABLEND-KTABL)/2
	LXI	H,KTABL
LOOP:	CCI				;COMPARE TABLE
	JRZ	FND
	INX	H
	JPE	LOOP			;CONT LOOKING
	JR	NFND
FND:	MOV	A,M			;NEW CODE
NFND:	ANI	7FH			;MASK DOWN
	POP	B
	POP	H
	RET
;*
;* THIS TABLE CAN BE EXTENDED IF DESIRED
KTABL:	DD	0E15DH			;]
	DD	0F15BH			;[
	DD	0A17EH			;~
	DD	0B15CH			;\
	DD	06015H			;CURSOR UP
TABLEND	EQU	$
	DS	KTABL+30-$,0		;ROOM FOR 15 CONVS
;*
;* CHECKSUM ROUTINE
CHKSM:	CALL	PTSTNG
	DC	'CHECKSUM '
	CALL	TAHEX
	MVI	B,0
CHKSMLP:	MOV	A,M
	ADD	B
	MOV	B,A
	CALL	BMP
	JRNZ	CHKSMLP
	MOV	A,B
	JMP	PT2
;*
;* WARM START
;*
WARM:	CALL	PTSTNG
	DC	'JUMP TO DOS'
	LXI	H,04E7H			;MDOS RESTART
	MOV	A,M
	CPI	0C3H
	JNZ	0			;CP/M RESTART
	PCHL				;MDOS WARM START
;*
;* KEYBOARD ECHO ROUTINE
ECHO:	CALL	PTSTNG
	DC	'ECHO KEYS '
ECOLP:	CALL	ESCAPE			;LOOK AT KEYBOARD
	CNZ	PTCN			;PRINT IF KEYPRESS
	JR	ECOLP			;CONTINUE LOOPING
;*
;*** MEMORY TEST ROUTINE ***
;*
TMEM:	CALL	PTSTNG
	DC	'TEST '
	CALL	TAHEX			;READ ADDRESSES
	LXI	B,5A5AH			;INI B,C
CYCL:	CALL	RNDM
	PUSH	B			;KEEP ALL REGS
	PUSH	H
	PUSH	D
TLOP:	CALL	RNDM
	MOV	M,B			;WRITE IN MEM
	CALL	BMP
	JNZ	TLOP			;REPEAT LOOP
	POP	D
	POP	H			;RESTORE ORIG
	POP	B			;VALUES OF
	PUSH	H
	PUSH	D
RLOP:	CALL	RNDM			;GEN NEW SEQ
	MOV	A,M			;READ MEM
	CMP	B			;COMP MEM
	CNZ	ERR			;CALL ERROR RTN
	CALL	BMP
	JNZ	RLOP
	POP	D
	POP	H
	MVI	A,'.'
	CALL	VIDEO
	JR	CYCL
;*** THIS ROUTINE GENERATES RANDOM NOS ***
RNDM:	CALL	PAUSE
	MOV	A,B			;LOOK AT B
	ANI	0B4H			;MASK BITS
	ANA	A			;CLEAR CY
	JPE	PEVE			;JUMP IF EVEN
	STC
PEVE:	MOV	A,C			;LOOK AT C
	RAL				;ROTATE CY IN
	MOV	C,A			;RESTORE C
	MOV	A,B			;LOOK AT B
	RAL				;ROTATE CY IN
	MOV	B,A			;RESTORE B
	RET				;RETURN W NEW B,C
;*
;*** ERROR PRINT OUT ROUTINE
;*
PTAD:	CALL	CRLF			;PRINT CR,LF
	CALL	PAUSE
	MOV	A,H			;PRINT
	CALL	PT2			;ASCII
	MOV	A,L			;CODES
	JMP	PT2S			;FOR ADDRESS
;*
ERR:	PUSH	PSW			;SAVE ACC
	CALL	PTAD			;PRINT ADD.
	MOV	A,B			;DATA
	CALL	PT2S			;WRITTEN
	POP	PSW			;DATA READ
PT2:	PUSH	PSW
	CALL	BINH
	POP	PSW
	JR	BINL
BINH:	RAR				;SHIFT RHT 4 BITS
	RAR
	RAR
	RAR
BINL:	ANI	0FH			;LOW 4 BITS
	ADI	48			;ASCII BIAS
	CPI	58			;DIGIT 0-9
	JC	PTCN
	ADI	7			;DIGIT A-F
	JMP	PTCN
;*
;* COMPARE ADDRESSES AND INCREMENT H
BMP:	MOV	A,E
	SUB	L
	JRNZ	GOON
	MOV	A,D
	SBB	H
GOON:	INX	H
	RET
;*
;* JUMP TO USER RAM
USER:	CALL	PTSTNG
	DC	'USER AREA'
	JMP	0100H
;*
;* JUMP TO RAM AT PR+1C00
RAM:	CALL	PTSTNG
	DC	'HI RAM'
	JMP	PR+1C00H
;*
;* JUMP TO RAM AT 0
LORAM:	CALL	PTSTNG
	DC	'LO RAM'
	JMP	0
;*
;* ZERO OR FILL MEMORY WITH A CONSTANT
ZEROM:	CALL	PTSTNG
	DC	'FILL '
	CALL	TAHEX			;READ ADDRESSES
	PUSH	H			;SAVE H
	CALL	AHE2			;READ 2 DIGITS
	XCHG
	XTHL				;RESTORE H,L
	POP	B
ZLOOP:	MOV	M,C			;WRITE INTO MEM
	CALL	BMP			;COMP ADD, INCR H
	RZ				;RETURN IF DONE
	JR	ZLOOP			;CONTINUE TIL DONE
;* EXCHANGE OR MOVE A BLOCK OF MEMORY
EXCHG:	MOV	B,A
	CALL	PTSTNG
	DC	'EXCHANGE '
	JR	MOVENTR
MOVEB:	MOV	B,A			;SAVE CODE
	CALL	PTSTNG
	DC	'MOVE '
MOVENTR:	CALL	TAHEX			;READ ADDRESSES
	PUSH	H
	CALL	AHEX
	XCHG
	XTHL				;BACK TO NORMAL
MLOOP:	MOV	C,M
	XTHL
	MOV	A,B
	CPI	'M'
	JRZ	NEXCH
	MOV	A,M
	XTHL
	MOV	M,A
	XTHL
NEXCH:	MOV	M,C
	INX	H
	XTHL
	CALL	BMP
	JZ	START
	JR	MLOOP
;* NON DESTRUCTIVE MEMORY TEST
NDMT:	CALL	PTSTNG
	DC	'MEM CHECK'
	LXI	H,0			;START AT ZERO
NDLOP:	MOV	C,M
	MVI	B,0FFH
	MOV	M,B
	MOV	A,M
	CMP	B
	JNZ	ERRJP			;PRINT ERROR
	MVI	B,0
	MOV	M,B
	MOV	A,M
	CMP	B
ERRJP:	JNZ	ERR
	MOV	M,C
	INX	H
	JR	NDLOP
;* COMPARE TWO BLOCKS OF MEMORY
COMPR:	CALL	PTSTNG
	DC	'COMPARE '
	CALL	TAHEX
	PUSH	H
	CALL	AHEX
	XCHG
VMLOP:	MOV	A,M
	INX	H
	XTHL
	CMP	M
	MOV	B,M
	CNZ	ERR
	CALL	BMP
	XTHL
	JRNZ	VMLOP
	POP	PSW
	RET
;* SEARCH FOR SPECIFIC CODES
FIND:	PUSH	PSW
	CALL	PTSTNG
	DC	'FIND-2 '
	JR	SRCHENT
SRCH:	PUSH	PSW
	CALL	PTSTNG
	DC	'SEARCH-1 '
SRCHENT:	CALL	TAHEX
	PUSH	H			;SAVE H
	CALL	AHE2			;READ 2 DIGITS
	XCHG				;H=CODE,D=F
	MOV	B,L			;PUT CODE IN B
	POP	H			;RESTORE H
	POP	PSW
	CPI	'S'
	PUSH	PSW
	JRZ	CONT
	PUSH	H
	CALL	AHE2			;READ 2 DIGITS
	XCHG
	MOV	C,L
	POP	H
CONT:	MOV	A,M			;READ MEMORY
	CMP	B			;COMPARE TO CODE
	JRNZ	SKP			;SKIP IF NO COMP
	POP	PSW			;FETCH CONTROL
	CPI	'S'
	PUSH	PSW
	JRZ	OBCP
	INX	H
	MOV	A,M
	DCX	H
	CMP	C
	JRNZ	SKP
OBCP:	INX	H
	MOV	A,M			;READ NEXT BYTE
	DCX	H			;DECR ADDRESS
	CALL	ERR			;PRINT CODES
SKP:	CALL	BMP			;CHECK IF DONE
	JRNZ	CONT			;BACK FOR MORE
	POP	PSW
	RET
;*
;* INPUT DATA FROM A PORT
PINPT:	CALL	PTSTNG
	DC	'INPUT '
	CALL	AHE2			;READ 2 DIGITS
	MOV	C,E
	INP	A
	JMP	PT2
;*
;* OUTPUT TO A PORT
POUTP:	CALL	PTSTNG
	DC	'OUTPUT '
	CALL	AHE2			;READ 2 DIGITS
	CALL	AHE2			;READ 2 DIGITS
	MOV	C,L
	OUTP	E
	RET
