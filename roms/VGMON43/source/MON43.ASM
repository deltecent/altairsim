VPAGE	EQU	PR+1000H		;SCREEN LOCATION
SPACE	EQU	20H
CLRSCRN	EQU	4
;*************************************************
;*                                               *
;* CONTROL CODE COMMANDS:                        *
;*     (B) HOME CURSOR                           *
;*     (D) CLEAR SCREEN                          *
;*     (E) PRINT CONTROL CODE                    *
;*     (H) BACKSPACE                             *
;*     (I) TAB                                   *
;*     (J) LINEFEED                              *
;*     (M) CARRIAGE RETURN                       *
;*     (N) NO CURSOR                             *
;*     (P) CLEAR TO END OF SCREEN                *
;*     (Q) CLEAR TO END OF LINE                  *
;*     (R) CURSOR DOWN                           *
;*     (T) TOGGLE REVERSE VIDEO                  *
;*     (U) CURSOR UP                             *
;*     (W) CURSOR LEFT                           *
;*     (X) CLEAR TO START OF LINE                *
;*     (Z) CURSOR RIGHT                          *
;*     ESC XY POSITION LEAD-IN                   *
;*                                               *
;*************************************************
;*
;* VIDEO BOARD PARAMETERS
HORIZ	EQU	80			;NO. OF CHARACTERS
VERT	EQU	24			;NO. OF LINES
;*
TVIDEO:	MVI	A,'T'-64		;TOGGLE VIDEO
;*
VIDEO:	PUSH	PSW
	PUSH	B
	PUSH	D
	PUSH	H
	ANI	07FH
	MOV	C,A
	LDA	BASE+800H
	CPI	0C3H			;PROM THERE?
	MOV	A,C
	CZ	BASE+800H		;CALL IT IF SO
DISPL:	CALL	LIFTCURS		;ERASE CURSOR
	LDA	XYFLAG
	ANA	A
	JRZ	NOXY
	DCR	A
	STA	XYFLAG
	JZ	YPOS
	JMP	XPOS
NOXY:	MOV	A,C			;RECOVER CHARACTER
	CPI	SPACE			;PRINTING CODE?
	JP	PRINT
	CPI	PCL-TABL		;TOO LARGE?
	JP	VRET
	PUSH	H			;CURSOR IN MEMORY
	LXI	H,TABL			;TABLE START
	MOV	E,A
	MVI	D,0
	DAD	D
	MOV	E,M
	LXI	H,PCL
	DAD	D
	XTHL				;RECOVER H
	RET				;EXECUTE ROUTINE
;* CONTROL CHARACTER JUMP TABLE
TABL:	DB	VRET-PCL		;@
	DB	VRET-PCL		;A
	DB	HOME-PCL		;B HOME CURSOR
	DB	VRET-PCL		;C
	DB	FORM-PCL		;D CLEAR SCREEN
	DB	PCL-PCL			;E PRT CONTROL
	DB	VRET-PCL		;F
	DB	VRET-PCL		;G
	DB	DBACKSP-PCL		;H BACKSPACE
	DB	TAB-PCL			;I TAB OVER
	DB	LINF-PCL		;J LINE FEED
	DB	VRET-PCL		;K
	DB	VRET-PCL		;L
	DB	CRET-PCL		;M CARRIAGE RET
	DB	VRET+3-PCL		;N NO CURSOR
	DB	VRET-PCL		;O
	DB	CLEND-PCL		;P CLR SCN TO END
	DB	CLLINE-PCL		;Q CLR LINE TO END
	DB	LINF-PCL		;R CURSOR DOWN
	DB	VRET-PCL		;S
	DB	TVIDF-PCL		;T TOGGLE VIDEO
	DB	CURSUP-PCL		;U CURSOR UP
	DB	VRET-PCL		;V
	DB	BACKSP-PCL		;W CURSOR LEFT
	DB	CLSTRT-PCL		;X CLR START OF LN
	DB	VRET-PCL		;Y
	DB	EOL-PCL			;Z CURSOR RIGHT
	DB	LEDIN-PCL		;[ ESC=XY LEADIN
;*
;* PRINT CODE IN B REGARDLESS
PCL:	MOV	C,B
;* PRINT THE CHARACTER ON THE SCREEN
PRINT:	LDA	VFL
	XRA	C
	MOV	M,A
;* EOL CHECKS THE CURS POS FOR END OF LINE
EOL:	LDA	CURPOS
	INR	A
	CPI	HORIZ
	JRC	TABRET
	XRA	A
	STA	CURPOS
;* MOVE DN 1 LINE
LINF:	LDA	LINENO
	CPI	VERT-1
	JRNZ	NOSCRL
;* SCROLL UP ONE LINE
SCROLL:	LXI	H,HORIZ
	LDED	TOSCN
	DAD	D
SCRL:	LDI
	LDI
	MOV	A,H
	CPI	HIGH (HORIZ*VERT+VPAGE)
	JRNZ	SCRL
	MOV	A,L
	CPI	LOW (HORIZ*VERT+VPAGE)
	JRNZ	SCRL
	LDA	LINENO
;* ERASE BOTTOM LINE
EBOTL:	XCHG
	MVI	B,HORIZ
ELOP:	MVI	M,SPACE
	INX	H
	DCR	B
	JRNZ	ELOP
	DCR	A
NOSCRL:	INR	A
	STA	LINENO
	JR	VRET
;*
;* ERASE BEFORE BACKSPACING
DBACKSP:	MVI	M,20H
	LDA	CURPOS
	ANA	A
	JRZ	VRET
	DCR	A
	DCX	H
	MVI	M,20H
	JR	TABRET
;* MOVE THE CURSOR BACK
BACKSP:	LDA	CURPOS
	DCR	A
	JP	TABRET
	JR	CRET
;* TAB OVER TO THE NEXT 8 MULTIPLE
TAB:	LDA	CURPOS
	ORI	7
	JR	EOL+3
;* CLEAR THE SCREEN AND HOME UP
FORM:	CALL	CLEAR
HOME:	XRA	A
	STA	LINENO
	STA	VFL			;CLR VID FLAG
;* CARRIAGE RETURN
CRET:	XRA	A
TABRET:	STA	CURPOS
;* RETURN TO THE CALLING ROUTINE
VRET:	CALL	LIFTCURS
	POP	H
	POP	D
	POP	B
	POP	PSW
	RET
TVIDF:	LDA	VFL
	XRI	80H
	STA	VFL
	JR	VRET
;*
;* MOVE THE CURSOR UP
CURSUP:	LDA	LINENO
	ANA	A
	JRZ	VRET
	DCR	A
STORLN:	STA	LINENO
	JR	VRET
;* CALCULATE MEM ADD FROM CURSOR POSITION
LIFTCURS:	LXI	H,HORIZ*VERT+VPAGE
	LXI	D,-HORIZ
	LDA	LINENO
CLOP:	INR	A
	DAD	D
	CPI	VERT
	JRNZ	CLOP			;OPTIMIZED AT BOTTOM
CFIN:	LDED	CURPOS
	MVI	D,0
	DAD	D
;* REVERSE THE VIDEO
	MOV	A,M
	XRI	80H
	MOV	M,A
	RET
;* CLEAR TO END OF SCREEN
CLEND:	CALL	WRSPC
	JR	VRET
;* CLEAR TO END OF LINE
CLLINE:	LDA	CURPOS
	MVI	M,20H
	INX	H
	INR	A
	CPI	50H
	JRNZ	CLLINE+3
	JR	VRET
;* CLEAR THE SCREEN
CLEAR:	LXI	H,VPAGE
	SHLD	TOSCN
	SHLD	XYFLAG
WRSPC:	MVI	M,20H
	INX	H
	MOV	A,H
	CPI	HIGH (VPAGE+2048)
	JRNZ	WRSPC
	RET
;*
;* PROCESS LEAD IN CODE
LEDIN:	MVI	A,2
	STA	XYFLAG
	JR	VRET
;*
;* SET X AND Y CURSOR POSITIONS
XPOS:	MOV	A,C
	CPI	80
	JRC	XINRG
	MVI	A,79
XINRG:	JR	TABRET
;*
YPOS:	MOV	A,C
	CPI	24
	JRC	YINRG
	MVI	A,23
YINRG:	JR	STORLN
;*
CLSTRT:	XRA	A
	STA	CURPOS
	CALL	LIFTCURS
	JR	CLLINE
MSEND	EQU	$
;* CURSOR STORAGE LOCATIONS
CURPOS	EQU	SPTR+0BH		;POS ON LINE
LINENO	EQU	CURPOS+1		;LINE NUMBER
VFL	EQU	LINENO+1		;REVERSE VID FLAG
WIDTH	EQU	VFL+1			;PRINT WIDTH
TOSCN	EQU	WIDTH+1			;TOP OF SCREEN
TCURPOS	EQU	TOSCN+2			;TEMP POSITION
;	LINK	'M5'
;* ADDITIONS TO 4.0 MONITOR
;	ORG	MSEND
;* PRINT A STRING
RPTSTNG:	CALL	CRLF			;CRLF FIRST
PTSTNG:	XTHL
	MOV	A,M
	INX	H
	XTHL
	ANA	A
	CALL	VIDEO			;PRINT IT
	RM
	JR	PTSTNG
;* SIGN ON MESSAGE
SIGN:	SHLD	39H			;REMNANT FROM RST 7 PATCH
	MVI	A,4			;CLEAR SCREEN
	CALL	VIDEO
	LXI	H,VPAGE+150H
	PUSH	H
	LXI	D,VPAGE+151H
	LXI	B,30H
	MVI	M,12H			;GRAPHIC CHARACTER
	LDIR
	POP	H
	LXI	D,VPAGE+1A0H
	LXI	B,640
	LDIR
	CALL	PTSTNG
	DB	27			;ESC
	DD	2007H			;X=32 Y=7
	DB	' VECTOR GRAPHIC '
	DB	27			;ESC
	DD	2008H			;X=32 Y=8
	DB	'    MONITOR     '
	DB	27			;ESC
	DD	2009H			;X=32 Y=9
	DB	'  VERSION 4.3   '
	DB	27			;ESC
	DD	8DH			;X=0 Y=13
	RET
PROMPT:	CALL	RPTSTNG
	DC	'Mon> '
	RET
;*
;*WIDE ASCII DUMP
WASCII:	CALL	PTSTNG
	DC	'ASCII DUMP '
	CALL	TAHEX
	CALL	HOMEC
;* MAKE A RULER FOR ASCII DUMP
RULELP:	MOV	A,B
	CPI	64
	JRZ	TERMLIN
	ANI	0FH
	JRZ	NUMBER
	ANI	3
	JRZ	MARKER
	MVI	A,' '
REENTR:	CALL	VIDEO
	INR	B
	JR	RULELP
MARKER:	MVI	A,'l'
	JR	REENTR
NUMBER:	MOV	A,B
	CALL	BINH
	JR	REENTR+3
;* TOGGLE REVERSE VIDEO
TERMLIN:	CALL	TVIDEO
WDMP1:	CALL	SETSCRLL
	CALL	PTAD
	MVI	C,63
	CALL	WDMP2
	JM	WDMP1
	RZ
WDMP2:	MOV	A,M
	MOV	B,A
	MVI	A,'E'-64
	CALL	VIDEO
	CALL	BMP
	RZ
	DCR	C
	RM
	JR	WDMP2
;* HOME CURSOR, PRINT "ADDR"
HOMEC:	CALL	RPTSTNG
	DB	'T'-64
	DC	'ADDR '
	MVI	B,0
	MVI	A,24
	STA	WIDTH
	RET
;* MAKE A RULER FOR HEX DUMP
HEXRLR:	MOV	A,B
	CPI	16
	JRZ	HEXRCT
	CALL	PT2S
	INR	B
	JR	HEXRLR
;* EXTEND FOR ASCII
HEXRCT:	CALL	SPCE
	CALL	SPCE
	MVI	B,0
HEXRLP:	MOV	A,B
	CPI	16
	RZ
	ANI	0FH
	CALL	BINL
	INR	B
	JR	HEXRLP
;* HEX DUMP ROUTINE
HEXRUL:	CALL	PTSTNG
	DC	'HEX DUMP '
	CALL	TAHEX
	CALL	HOMEC
	CALL	HEXRLR
	CALL	TVIDEO
	CALL	SETSCRLL
HLP1:	CALL	PTAD
	PUSH	H
	PUSH	D
	MVI	C,16
HLP2:	MOV	A,M
	CALL	PT2S
	INX	H
	DCR	C
	JNZ	HLP2
	POP	D
	POP	H
	MVI	C,15
	CALL	SPCE
	CALL	SPCE
	CALL	WDMP2
	JM	HLP1-3
	RET
;* CHECK TO SET SCROLL POINT
SETSCRLL:	LDA	WIDTH
	DCR	A
	STA	WIDTH
	JRNZ	CTSCRL
	LXI	B,VPAGE+50H		;2ND LINE
	SBCD	TOSCN			;SCROLL POINT
CTSCRL:	RET
;*
;* PROGRAM MEMORY
PROGRAM:	CALL	PTSTNG
	DC	'PROGRAM '
	CALL	AHEX			;ADDR IN HL
	SDED	TCURPOS
	CALL	HOMEC			;PRINT "ADDR"
	CALL	HEXRLR
	CALL	TVIDEO
	XRA	A
	STA	WIDTH
	CALL	PRT1LINE		;PRINT LINE CONT H
POLLOOP:	CALL	ESCAPE
	CALL	HEX
	LHLD	TCURPOS
	JRNC	MODMEM
;* CONTROL CODE TABLE
	CPI	' '
	JRZ	CSRT
	CPI	8
	JRZ	CSLT
	CPI	'R'-64
	JRZ	CSDN
	CPI	'U'-64
	JRZ	CSUP
	CPI	'W'-64
	JRZ	CSLT
	CPI	'Z'-64
	JRZ	CSRT
	JR	POLLOOP
;* MODIFY A MEMORY LOCATION
MODMEM:	LHLD	TCURPOS
	MOV	C,A
	LDA	WIDTH
	ANA	A
	MOV	A,M
	JRZ	LSNIBL
	ANI	0F0H
	ORA	C
REMEM:	MOV	M,A
	LDA	WIDTH
	XRI	1
	JRNZ	RTRTN+1
	JR	CSRT
LSNIBL:	RAL
	RAL
	RAL
	RAL
	ANI	0F0H
	ORA	C
	RRC
	RRC
	RRC
	RRC
	JR	REMEM
;* MOVE UP ONE LINE
CSUP:	LXI	D,-16
	DAD	D
	JR	RTRTN
;* MOVE DOWN ONE LINE
CSDN:	LXI	D,16
	JR	CSUP+3
;* MOVE RIGHT ONE SPACE
CSRT:	INX	H
	JR	RTRTN
;* MOVE LEFT ONE SPACE
CSLT:	DCX	H
;*
RTRTN:	XRA	A
	STA	WIDTH
	SHLD	TCURPOS
UPAROW:	MVI	A,'U'-64
	CALL	VIDEO
	JR	POLLOOP-3
;* PRINT A LINE CONTAINING ((H))
PRT1LINE:	LHLD	TCURPOS
	PUSH	H
	POP	D
	MOV	A,L
	ORI	0FH
	MOV	E,A
	ANI	0F0H
	MOV	L,A
	CALL	HLP1
;* NOW PUT CURSOR WHERE IT GOES
	CALL	LIFTCURS
	LHLD	TCURPOS
	MOV	A,L
	ANI	0FH
	MOV	L,A
	MVI	A,5
PLOP1:	DCR	L
	JM	PGCONT
	ADI	3
	JR	PLOP1
PGCONT:	MOV	L,A
	LDA	WIDTH
	ADD	L
;* A = 5+3*L+W
	STA	CURPOS
	JMP	LIFTCURS
;*
;*
;* DISPLAY REGISTERS
DREGS:	CALL	PTSTNG
	DC	'REGISTERS'
;* DUMP REGISTERS AFTER ENTRY FROM RST 7
DUMPREGS:	XTHL
	PUSH	PSW
	CALL	DISPREGS
	DCX	H			;GET BREAK ADD
	CALL	PTAD
	POP	H
	PUSH	B
	CALL	PRTFLGS
	POP	B
	CALL	PTAD+3			;PRINT AF
	POP	H
	SHLD	HLTEMP
	CALL	PTHREE			;PRINT B D H
	DB	0DDH,0E5H		;PUSH IX
	POP	H
	CALL	PTAD+3			;PRINT IX
	DB	0FDH,0E5H		;PUSH IY
	POP	H
	CALL	PTAD+3			;PRINT IY
	LXI	H,0
	DAD	SP
	SHLD	SPTEMP
	CALL	PTAD+3			;PRINT SP
	EXAF
	PUSH	PSW
	POP	H
	CALL	PTAD+3
	EXX
	CALL	PTHREE
	EXX
	LDAX	B
	CALL	PT2S
	LDAX	D
	CALL	PT2S
	LHLD	HLTEMP
	MOV	A,M
	CALL	PT2S
	LHLD	SPTEMP
	SPHL
	POP	H
	CALL	PTAD+3
	JMP	CLRBRK			;CLEAR BREAKPOINT
;*
PT2S:	CALL	PT2			;PRINT 2 CHARS
	JMP	SPCE			;PRINT SPACE
;* DISPLAY REGISTER HEADER ON SCREEN
DISPREGS:	CALL	RPTSTNG
	DB	'T'-64
	DB	'ADDR FLAGS  AF   BC   DE'
	DB	'   HL   IX   IY   SP '
	DB	'  AF'
	DB	27H			;'
	DB	'  BC'
	DB	27H
	DB	'  DE'
	DB	27H
	DB	'  HL'
	DB	27H
	DB	' @B @D @H @SP '
	DB	'T'+64
	RET
;*
;* PRINT FLAGS
PRTFLGS:	LXI	B,405AH			;Z
	CALL	MASKFLG
	LXI	B,143H			;C
	CALL	MASKFLG
	LXI	B,804DH			;M
	CALL	MASKFLG
	LXI	B,445H			;E
	CALL	MASKFLG
	LXI	B,1048H			;H
	CALL	MASKFLG
	JMP	SPCE
;*
;* PRINT BC DE HL IN ORDER
PTHREE:	PUSH	H
	PUSH	B
	POP	H
	CALL	PTAD+3
	PUSH	D
	POP	H
	CALL	PTAD+3
	POP	H
	JMP	PTAD+3
;*
MASKFLG:	MOV	A,L
	ANA	B
	MVI	A,20H
	JZ	VIDEO
	MOV	A,C
	JMP	VIDEO
;*
;* SET BREAKPOINT
SETBRK:	CALL	PTSTNG
	DC	'BREAK AT '
	CALL	AHEX
	LDAX	D
	STA	BRKCODE
	SDED	BKPTLOC
	MVI	A,0FFH			;RST 7
	STAX	D
	RET
;*
;* EXTERNAL COMMUNICATIONS
EXTCOM:	CALL	PTSTNG
	DC	'EXT COM '
RECEIVE:	IN	5
	ANI	2
	JRZ	NEXCHR
	IN	4
	CALL	VIDEO
NEXCHR:	CALL	ESCAPE
	JRZ	RECEIVE
	OUT	4
	JR	RECEIVE
;*
;* TEMPORARY STORAGE LOCATIONS FOR REGISTERS,ETC.
HLTEMP	EQU	TCURPOS+2
SPTEMP	EQU	HLTEMP+2
BKPTLOC	EQU	SPTEMP+2		;BREAKPT LOCATION
BRKCODE	EQU	BKPTLOC+2		;CODE AT BREAKPT
XYFLAG	EQU	BRKCODE+1		;CURSOR XY FLAG

;
;  Not in the listing, which ends at E7EE. The ROM has these bytes, and the
;  listed checksum of 43 includes the 66 at E7FF.
;
	DS	MONIT+7FFH-$,0
	DB	66H

	.DEPHASE
	END
