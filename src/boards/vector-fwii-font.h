#pragma once
//
// The FlashWriter II character generator (src/boards/vector-fwii.cpp).
//
// The 128 glyphs of the board's ROM at U22: one scan line per byte, 10 lines per
// glyph, indexed by the low 7 bits of a screen byte (D7 is reverse video, not part of
// the glyph). Within a line byte, bit 7 is the leftmost dot, as the chart labels it,
// D7 to D0 from the left.
//
// 0x00-0x1F are block graphics. A cell is cut into six blocks, two across and three
// down (lines 0-2, 3-6 and 7-9). Five code bits light one block each:
//
//     bit 0  lower right     bit 3  lower left
//     bit 1  middle right    bit 4  middle left
//     bit 2  upper right     (the upper left block has no bit)
//
// Provenance: read by machine from the character chart in Section IV of the manual,
// at 300 dpi. No dump of the ROM exists to check it against.
//
//   a. Rev 3 (deramp.com), PDF page 29, the normal chart. This table is that reading.
//   b. Rev 4-A (s100computers.com), PDF page 29, the normal chart.
//   c. Rev 3, PDF page 30, and Rev 4-A, PDF page 30, the reverse chart. Inverted, these
//      are a check on 0x00-0x1F only. Every square of cells 0xA0-0xFF prints open in
//      both scans, so 0x20-0x7F have no reverse reading.
//
// Readings a and b agree on 124 of 128 cells, dot for dot. Readings a and c agree on all
// 32 graphics cells. The four cells on which a and b differ were settled like this:
//
//   0x04 line 9, D5        b reads a faint dot. Open in a and c, and the dot would
//                          break a whole block, so it is a mark in the scan.
//   0x0D line 0, D3 and D2 b reads these dots as half filled. Filled in a and c, and
//   0x0E line 0, D2        they belong to a whole filled block.
//   0x7F all lines         b breaks up, because its filled squares print with holes.
//                          Crops of both scans, read by eye, show the same checkerboard.
//
// The one thin cell in reading a is 0x70 'p', where some filled squares print faint.
// Reading b gives the same dots there.
//
// The board only calls glyphRow(); nothing else depends on the storage layout.

