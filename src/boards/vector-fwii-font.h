// One scan line of a glyph as an 8-bit column pattern (bit 7 = leftmost dot).
inline uint8_t glyphRow(uint8_t code, int row) {
    if (row < 0 || row >= kRows) return 0;
    code &= 0x7F;
    return charset()[code][row];
}

