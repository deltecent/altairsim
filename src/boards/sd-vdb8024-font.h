// One scan line (0..kRows-1) of a glyph, bit 7 = leftmost dot. `code` is the character
// code (screen byte & 0x7F); control codes 0x00-0x1F are blank on a terminal.
//
// A stored byte's bit 0 is the DESCENDER FLAG (see the header note): a flagged byte is
// drawn on the two bottom lines (8/9) of the 10-line field, in flag order; every other
// byte draws at its own index (line 0..7). So a plain glyph fills lines 0..7 and a
// descender glyph keeps its body on the baseline while its tail hangs at lines 8/9.
inline uint8_t glyphRow(uint8_t code, int row) {
    if (code < 0x20 || row < 0 || row >= kRows) return 0;
    const uint8_t* g = charset()[code & 0x7F];
    if (row <= 7) {
        uint8_t b = g[row];
        return (b & 0x01) ? 0 : (uint8_t)(b & 0xFE);  // a descender byte vacates its top line
    }
    // Bottom lines 8/9: the (row-8)-th descender-flagged byte, in stored order.
    int want = row - 8, seen = 0;
    for (int i = 0; i < 8; ++i)
        if (g[i] & 0x01) {
            if (seen == want) return (uint8_t)(g[i] & 0xFE);
            ++seen;
        }
    return 0;
}

