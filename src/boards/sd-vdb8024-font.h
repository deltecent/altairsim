// PROVENANCE: the authentic VDB-8024 font, transcribed from the manual's Appendix E,
// "VDB 8024 CHARACTER GENERATOR DATA" (SDS_VDB8024.pdf) -- an SD Systems Z80 assembler
// listing ("CHARACTER GENERATOR SOFTWARE VERSION 1.0", ORG 0, ERRORS=0000), 8 DEFB bytes
// per glyph, glyph address = ASCII code x 8. The byte values below are the assembled
// object code read from that listing; the printable set 0x20-0x7F was transcribed, and
// 0x00-0x1F (control cells, never displayed on a terminal) are left blank. Read from a
// 300 DPI render and cross-checked against the listing's dual CODE/DEFB columns.
//
// STORAGE / DOT CONVENTION: one byte per stored row, byte 0 first; within a byte the
// SEVEN dots are bits 7..1 (bit 7 = LEFTMOST dot), giving a 7-wide glyph in an 8-wide
// cell (a natural 1-dot right gap). Bit 0 is NOT a dot -- it is the DESCENDER FLAG.
//
// THE DESCENDER FLAG (reference/SD Systems VDB-8024.md 3). The cell is a 7x8 dot glyph
// displayed in a 7x10 field: two extra scan lines at the bottom give true lower-case
// descenders. A stored byte with bit 0 SET is a descender row -- it is drawn on the two
// BOTTOM lines (8/9) of the field instead of at its natural top position. That is how g,
// j, p, q, y (and comma, semicolon, '?') carry their tail: their leading byte(s) have
// bit 0 set and hold the pixels that belong below the baseline. glyphRow() below folds
// that relocation in, so the board just asks for scan line 0..9 and renders it flat.
//
// The board only ever calls glyphRow(); nothing else depends on the layout.

