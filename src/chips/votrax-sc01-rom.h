// One phoneme's fields, in the patent's names (Fig. 12).
struct Phone {
    uint8_t code;       // P5..P0
    uint8_t f1, f2, f2q, f3;   // formant frequencies and the F2 Q (4 bits)
    uint8_t fc;         // how much of the noise goes through F2 (4 bits)
    uint8_t va;         // voice amplitude (4 bits)
    uint8_t fa;         // fricative (noise) amplitude (4 bits)
    uint8_t vd;         // voice delay: the tick at which VA starts to move (4 bits)
    uint8_t cld;        // closure delay: the tick at which FA, FC and CL take effect (4 bits)
    bool    cl;         // closure: the output is shut off from CLD on
    uint8_t duration;   // 7 bits; one tick is 4 * duration + 1 cycles of master / 36
};

// The value of the word's bits `b[0]`, `b[1]`, ... with b[0] as the MSB.
template <int N>
constexpr uint8_t gather(uint64_t w, const int (&b)[N]) {
    uint8_t v = 0;
    for (int i = 0; i < N; ++i) v = static_cast<uint8_t>((v << 1) | ((w >> b[i]) & 1));
    return v;
}

// The word at `index` (0..63) as a 64-bit value.
inline uint64_t word(int index) {
    uint64_t w = 0;
    for (int i = 7; i >= 0; --i) w = (w << 8) | image()[index * 8 + i];
    return w;
}

// Decode the word at `index`. The two delays have their bits in the reverse order of the
// other fields on the die. The die's names for them are swapped from the patent's: the one
// at bits 29-35 times FA and CL, which the patent calls CLD.
inline Phone decode(int index) {
    const uint64_t w = word(index);
    Phone p{};
    p.code     = static_cast<uint8_t>((w >> 56) & 0x3F);
    p.f1       = gather(w, {0, 7, 14, 21});
    p.va       = gather(w, {1, 8, 15, 22});
    p.f2       = gather(w, {2, 9, 16, 23});
    p.fc       = gather(w, {3, 10, 17, 24});
    p.f2q      = gather(w, {4, 11, 18, 25});
    p.f3       = gather(w, {5, 12, 19, 26});
    p.fa       = gather(w, {6, 13, 20, 27});
    p.vd       = gather(w, {34, 32, 30, 28});
    p.cld      = gather(w, {35, 33, 31, 29});
    p.cl       = ((w >> 36) & 1) != 0;
    p.duration = static_cast<uint8_t>(gather(~w, {37, 38, 39, 40, 41, 42, 43}));
    return p;
}

// The fields of phoneme `code` (0..63). Every code is in the ROM exactly once.
inline Phone lookup(uint8_t code) {
    for (int i = 0; i < kWords; ++i) {
        Phone p = decode(i);
        if (p.code == (code & 0x3F)) return p;
    }
    return Phone{};
}

