//
// The Votrax SC-01-A phoneme ROM (src/chips/votrax-sc01.cpp). It is INSIDE the chip:
// the bus cannot reach it, so it is compiled in here and is not a roms/ image.
//
// PROVENANCE. No period document gives these values. They were read from a decapped
// SC-01-A in 2007. The image is MAME's `sc01a.bin`: 512 bytes, CRC32 fc416227,
// SHA1 1d6da90b1807a01b5e186ef08476119a862b5e6d. docs/sources.md records the terms.
// tests/test_votrax_sc01.cpp checks the CRC of this array.
//
// THE LAYOUT. Patent US 4,433,210 Fig. 12 gives the logical ROM: 64 phonemes, each with
// F1 F2 FC F3 F2Q VA FA (4 bits each), the two delays, the closure bit and a 7-bit
// duration (reference/Votrax SC-01 patent US4433210.md section 3). The die stores the
// same fields in a different bit order. The image is 64 little-endian 64-bit words, one
// per phoneme, in no particular order:
//
//   bits 56-61  the phoneme code that the word belongs to (P5..P0)
//   bit 36      CL, closure
//   bits 37-43  the duration, inverted, MSB at bit 37
//   the rest    the 4-bit fields, one bit in each 7-bit group (see decode()).
//
// The bit positions are a die fact. They were taken from MAME's votrax.cpp, which is
// read here as a reference only (DESIGN.md 0.1). decode() is our own.

